use super::*;
pub(super) fn growth_rules(p: &mut Assembler, thresholds: u32, growth: u32, base: u32) {
    const LEVEL: u16 = STATS + 2;
    const EXPERIENCE: u16 = STATS + 0x20;
    const SHOWN: u16 = STATS + 0x24;
    p.label("vm_level").assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    abs(p, M::Lda, SHOWN);
    word(p, M::Cmp, 57);
    m8(p);
    branch(p, M::Bcs, "vm_level_up");
    jump(p, "vm_branch");
    p.label("vm_level_up");
    call(p, "battle_grow");
    jump(p, "vm_next8");
    p.label("vm_gems_clear").assume_mode(CpuMode::NATIVE_M8_X16);
    program(p, M::Lda, base, 1);
    emit(p, M::Cmp, A::Immediate, O::Byte(2));
    branch(p, M::Bne, "vm_gems_clear_done");
    m16(p);
    abs(p, M::Stz, SHOWN);
    m8(p);
    p.label("vm_gems_clear_done");
    jump(p, "vm_next4");
    p.label("vm_gems").assume_mode(CpuMode::NATIVE_M8_X16);
    emit(p, M::Ldx, A::Absolute, O::Word(PC));
    m16(p);
    program(p, M::Lda, base, 4);
    abs(p, M::Cmp, LATCH);
    branch(p, M::Beq, "vm_gems_counted");
    abs(p, M::Sta, LATCH);
    m8(p);
    call(p, "battle_gem_delta");
    m16(p);
    p.label("vm_gems_counted");
    abs(p, M::Lda, GEMS);
    branch(p, M::Beq, "vm_gems_done");
    abs(p, M::Inc, SHOWN);
    abs(p, M::Dec, GEMS);
    abs(p, M::Lda, LATCH);
    abs(p, M::Sta, PC);
    m8(p);
    jump(p, "battle_vm_step");
    p.label("vm_gems_done").assume_mode(CpuMode::NATIVE_M16_X16);
    word(p, M::Lda, 0xffff);
    abs(p, M::Sta, LATCH);
    m8(p);
    jump(p, "vm_next8");
    p.label("battle_gem_delta")
        .assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    abs(p, M::Stz, GEMS);
    abs(p, M::Lda, LEVEL);
    word(p, M::Cmp, 99);
    branch(p, M::Bcc, "battle_gem_delta_count");
    m8(p);
    implied(p, M::Rts);
    p.label("battle_gem_delta_count")
        .assume_mode(CpuMode::NATIVE_M16_X16);
    abs(p, M::Sta, REACHED);
    p.label("battle_gem_delta_level");
    abs(p, M::Lda, REACHED);
    word(p, M::Cmp, 99);
    branch(p, M::Bcs, "battle_gem_delta_progress");
    emit(p, M::Asl, A::Accumulator, O::None);
    emit(p, M::Asl, A::Accumulator, O::None);
    implied(p, M::Tax);
    emit(p, M::Lda, A::AbsoluteLongX, O::Long(thresholds + 2));
    abs(p, M::Cmp, EXPERIENCE + 2);
    branch(p, M::Bcc, "battle_gem_delta_passed");
    branch(p, M::Bne, "battle_gem_delta_progress");
    emit(p, M::Lda, A::AbsoluteLongX, O::Long(thresholds));
    abs(p, M::Cmp, EXPERIENCE);
    branch(p, M::Beq, "battle_gem_delta_passed");
    branch(p, M::Bcs, "battle_gem_delta_progress");
    p.label("battle_gem_delta_passed");
    abs(p, M::Inc, REACHED);
    branch(p, M::Bra, "battle_gem_delta_level");
    p.label("battle_gem_delta_progress");
    abs(p, M::Lda, REACHED);
    emit(p, M::Asl, A::Accumulator, O::None);
    emit(p, M::Asl, A::Accumulator, O::None);
    implied(p, M::Tax);
    emit(p, M::Lda, A::AbsoluteLongX, O::Long(thresholds));
    implied(p, M::Sec);
    emit(p, M::Sbc, A::AbsoluteLongX, O::Long(thresholds - 4));
    abs(p, M::Sta, SPAN);
    emit(p, M::Lda, A::AbsoluteLongX, O::Long(thresholds + 2));
    emit(p, M::Sbc, A::AbsoluteLongX, O::Long(thresholds - 2));
    abs(p, M::Sta, SPAN + 2);
    abs(p, M::Lda, EXPERIENCE);
    implied(p, M::Sec);
    emit(p, M::Sbc, A::AbsoluteLongX, O::Long(thresholds - 4));
    abs(p, M::Sta, AMOUNT);
    abs(p, M::Lda, EXPERIENCE + 2);
    emit(p, M::Sbc, A::AbsoluteLongX, O::Long(thresholds - 2));
    abs(p, M::Sta, AMOUNT + 2);
    word(p, M::Lda, 57);
    abs(p, M::Sta, FACTOR);
    m8(p);
    call(p, "battle_multiply");
    call(p, "battle_divide_wide");
    m16(p);
    abs(p, M::Lda, AMOUNT + 2);
    branch(p, M::Bne, "battle_gem_delta_full");
    abs(p, M::Lda, AMOUNT);
    word(p, M::Cmp, 57);
    branch(p, M::Bcc, "battle_gem_delta_sum");
    p.label("battle_gem_delta_full");
    word(p, M::Lda, 57);
    p.label("battle_gem_delta_sum");
    abs(p, M::Sta, GEMS);
    abs(p, M::Lda, REACHED);
    implied(p, M::Sec);
    abs(p, M::Sbc, LEVEL);
    implied(p, M::Tax);
    p.label("battle_gem_delta_whole");
    emit(p, M::Cpx, A::Immediate, O::Word(0));
    branch(p, M::Beq, "battle_gem_delta_less");
    abs(p, M::Lda, GEMS);
    implied(p, M::Clc);
    word(p, M::Adc, 57);
    abs(p, M::Sta, GEMS);
    implied(p, M::Dex);
    branch(p, M::Bra, "battle_gem_delta_whole");
    p.label("battle_gem_delta_less");
    abs(p, M::Lda, GEMS);
    implied(p, M::Sec);
    abs(p, M::Sbc, SHOWN);
    abs(p, M::Sta, GEMS);
    m8(p);
    implied(p, M::Rts);
    p.label("battle_divide_wide")
        .assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    abs(p, M::Stz, WORK);
    abs(p, M::Stz, WORK + 2);
    emit(p, M::Ldx, A::Immediate, O::Word(32));
    p.label("battle_divide_wide_bit");
    abs(p, M::Asl, AMOUNT);
    abs(p, M::Rol, AMOUNT + 2);
    abs(p, M::Rol, WORK);
    abs(p, M::Rol, WORK + 2);
    abs(p, M::Lda, WORK);
    implied(p, M::Sec);
    abs(p, M::Sbc, SPAN);
    abs(p, M::Sta, ROLL);
    abs(p, M::Lda, WORK + 2);
    abs(p, M::Sbc, SPAN + 2);
    branch(p, M::Bcc, "battle_divide_wide_next");
    abs(p, M::Sta, WORK + 2);
    abs(p, M::Lda, ROLL);
    abs(p, M::Sta, WORK);
    abs(p, M::Inc, AMOUNT);
    p.label("battle_divide_wide_next");
    implied(p, M::Dex);
    branch(p, M::Bne, "battle_divide_wide_bit");
    m8(p);
    implied(p, M::Rts);
    p.label("battle_grow").assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    abs(p, M::Lda, LEVEL);
    word(p, M::Cmp, 99);
    branch(p, M::Bcs, "battle_grow_refill");
    abs(p, M::Inc, LEVEL);
    for (field, step) in [
        (6u16, 4u16),
        (0xa, 4),
        (0xc, 2),
        (0xe, 2),
        (0x10, 1),
        (0x12, 1),
    ] {
        abs(p, M::Lda, STATS + field);
        implied(p, M::Clc);
        word(p, M::Adc, step);
        abs(p, M::Sta, STATS + field);
    }
    p.label("battle_grow_refill");
    abs(p, M::Lda, STATS + 6);
    abs(p, M::Sta, STATS + 4);
    abs(p, M::Lda, STATS + 0xa);
    abs(p, M::Sta, STATS + 8);
    m8(p);
    abs(p, M::Stz, GROWTH_NOTICE);
    emit(p, M::Ldx, A::Immediate, O::Word(0));
    p.label("battle_grow_row");
    emit(p, M::Lda, A::AbsoluteLongX, O::Long(growth));
    abs(p, M::Cmp, LEVEL);
    branch(p, M::Bne, "battle_grow_next");
    abs(p, M::Lda, LEVEL + 1);
    branch(p, M::Bne, "battle_grow_next");
    implied(p, M::Txa);
    emit(p, M::Lsr, A::Accumulator, O::None);
    emit(p, M::Inc, A::Accumulator, O::None);
    abs(p, M::Sta, GROWTH_NOTICE);
    m16(p);
    emit(p, M::Lda, A::AbsoluteLongX, O::Long(growth + 1));
    word(p, M::And, 0xff);
    implied(p, M::Tax);
    m8(p);
    emit(p, M::Inc, A::AbsoluteX, O::Word(crate::sfc_battle::LEARNED));
    implied(p, M::Rts);
    p.label("battle_grow_next");
    implied(p, M::Inx);
    implied(p, M::Inx);
    emit(p, M::Cpx, A::Immediate, O::Word(32));
    branch(p, M::Bne, "battle_grow_row");
    implied(p, M::Rts);
}
pub(super) fn reward(p: &mut Assembler) {
    p.label("vm_reward").assume_mode(CpuMode::NATIVE_M8_X16);
    call(p, "battle_pair");
    m16(p);
    abs(p, M::Lda, GOLD);
    implied(p, M::Clc);
    its(p, M::Adc, 0x1c);
    abs(p, M::Sta, GOLD);
    word(p, M::Lda, 0);
    abs(p, M::Adc, GOLD + 2);
    abs(p, M::Sta, GOLD + 2);
    branch(p, M::Beq, "vm_reward_gold");
    word(p, M::Lda, 0xffff);
    abs(p, M::Sta, GOLD);
    abs(p, M::Stz, GOLD + 2);
    p.label("vm_reward_gold");
    m8(p);
    byte(p, M::Lda, 0);
    own(p, M::Sta, 0x60);
    its(p, M::Lda, 0x1a);
    branch(p, M::Beq, "vm_reward_done");
    abs(p, M::Sta, ACTION);
    m16(p);
    its(p, M::Lda, 0x1b);
    word(p, M::And, 0xff);
    abs(p, M::Sta, DIVISOR);
    m8(p);
    call(p, "battle_rng");
    m16(p);
    abs(p, M::Lda, crate::sfc_battle_act::RANDOM);
    m8(p);
    branch(p, M::Bne, "vm_reward_done");
    m16(p);
    abs(p, M::Lda, ACTION);
    word(p, M::And, 0xff);
    implied(p, M::Sec);
    word(p, M::Sbc, u16::from(crate::sfc_b1_menu::FIRST_ITEM));
    implied(p, M::Tax);
    m8(p);
    emit(p, M::Lda, A::AbsoluteX, O::Word(INVENTORY));
    emit(p, M::Cmp, A::Immediate, O::Byte(99));
    branch(p, M::Bcs, "vm_reward_done");
    emit(p, M::Inc, A::AbsoluteX, O::Word(INVENTORY));
    registers(p);
    abs(p, M::Lda, ACTION);
    implied(p, M::Sec);
    byte(p, M::Sbc, 40);
    emit(p, M::Cmp, A::Immediate, O::Byte(13));
    branch(p, M::Bcs, "vm_reward_done");
    emit(p, M::Inc, A::Accumulator, O::None);
    own(p, M::Sta, 0x60);
    p.label("vm_reward_done");
    jump(p, "vm_next4");
}
