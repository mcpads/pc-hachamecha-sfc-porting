use super::actors::{
    assess, choose_arle, descriptor_message, durations, field_steps, message, pose, status,
};
use super::rewards::{growth_rules, reward};
use super::*;
pub(super) fn rules(p: &mut Assembler, thresholds: u32, growth: u32, base: u32, bits: u32) {
    p.label("vm_field_steps")
        .assume_mode(CpuMode::NATIVE_M8_X16);
    field_steps(p, STATS);
    jump(p, "vm_next4");
    p.label("field_shortage")
        .assume_mode(CpuMode::NATIVE_M8_X16);
    field_steps(p, STATS);
    implied(p, M::Rts);
    p.label("vm_setup").assume_mode(CpuMode::NATIVE_M8_X16);
    call(p, "battle_setup");
    jump(p, "vm_next4");
    p.label("vm_order_index")
        .assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    abs(p, M::Stz, ORDER_INDEX);
    m8(p);
    jump(p, "vm_next4");
    p.label("vm_order").assume_mode(CpuMode::NATIVE_M8_X16);
    call(p, "battle_order");
    jump(p, "vm_next4");
    p.label("vm_script").assume_mode(CpuMode::NATIVE_M8_X16);
    program(p, M::Lda, base, 1);
    branch(p, M::Bne, "vm_script_reaction");
    call(p, "battle_action_script");
    jump(p, "vm_next4");
    p.label("vm_script_reaction");
    abs(p, M::Sta, ACTION);
    call(p, "battle_pair");
    abs(p, M::Lda, ACTION);
    emit(p, M::Cmp, A::Immediate, O::Byte(1));
    branch(p, M::Bne, "vm_script_self");
    its(p, M::Lda, 0x44);
    abs(p, M::Cmp, CURRENT_INDEX);
    branch(p, M::Beq, "vm_script_facing");
    abs(p, M::Lda, CURRENT_INDEX);
    emit(p, M::Cmp, A::Immediate, O::Byte(1));
    branch(p, M::Bne, "vm_script_none");
    own(p, M::Lda, 0x40);
    branch(p, M::Beq, "vm_script_none");
    p.label("vm_script_facing");
    own(p, M::Lda, 0x45);
    byte(p, M::And, 0x40);
    branch(p, M::Beq, "vm_script_none");
    abs(p, M::Lda, TARGET_INDEX);
    branch(p, M::Bra, "vm_script_run");
    p.label("vm_script_self");
    own(p, M::Lda, 0x4e);
    emit(p, M::Cmp, A::Immediate, O::Byte(99));
    branch(p, M::Bne, "vm_script_none");
    abs(p, M::Lda, CURRENT_INDEX);
    p.label("vm_script_run");
    emit(p, M::Ldy, A::Immediate, O::Word(2));
    call(p, "battle_run_script");
    p.label("vm_script_none");
    jump(p, "vm_next4");
    p.label("vm_choose").assume_mode(CpuMode::NATIVE_M8_X16);
    call(p, "battle_choose");
    branch(p, M::Bcc, "vm_choose_done");
    implied(p, M::Rts);
    p.label("vm_choose_done");
    jump(p, "vm_next4");
    choose_arle(p);
    p.label("vm_act").assume_mode(CpuMode::NATIVE_M8_X16);
    program(p, M::Lda, base, 1);
    branch(p, M::Bne, "vm_act_apply");
    call(p, "battle_act");
    jump(p, "vm_next4");
    p.label("vm_act_apply");
    call(p, "battle_apply");
    jump(p, "vm_next4");
    p.label("vm_request").assume_mode(CpuMode::NATIVE_M8_X16);
    program(p, M::Lda, base, 1);
    abs(p, M::Sta, ACTION);
    call(p, "battle_pair");
    abs(p, M::Lda, ACTION);
    branch(p, M::Bne, "vm_request_not_0");
    byte(p, M::Lda, 1);
    own(p, M::Sta, 0x41);
    byte(p, M::Lda, 3);
    own(p, M::Sta, 0x43);
    branch(p, M::Bra, "vm_request_body");
    p.label("vm_request_not_0");
    emit(p, M::Cmp, A::Immediate, O::Byte(1));
    branch(p, M::Bne, "vm_request_not_1");
    byte(p, M::Lda, 1);
    its(p, M::Sta, 0x41);
    jump(p, "vm_next4");
    p.label("vm_request_not_1");
    emit(p, M::Cmp, A::Immediate, O::Byte(2));
    branch(p, M::Bne, "vm_request_done");
    own(p, M::Lda, 0x59);
    branch(p, M::Beq, "vm_request_done");
    byte(p, M::Lda, 1);
    own(p, M::Sta, 0x41);
    byte(p, M::Lda, 4);
    own(p, M::Sta, 0x43);
    byte(p, M::Lda, 6);
    own(p, M::Sta, 0x42);
    p.label("vm_request_body");
    p.label("vm_request_done");
    jump(p, "vm_next4");
    p.label("vm_wait").assume_mode(CpuMode::NATIVE_M8_X16);
    program(p, M::Lda, base, 1);
    abs(p, M::Sta, ACTION);
    call(p, "battle_pair");
    abs(p, M::Lda, ACTION);
    emit(p, M::Cmp, A::Immediate, O::Byte(1));
    branch(p, M::Bne, "vm_wait_actor");
    its(p, M::Lda, 0x43);
    branch(p, M::Bra, "vm_wait_busy");
    p.label("vm_wait_actor");
    own(p, M::Lda, 0x43);
    p.label("vm_wait_busy");
    branch(p, M::Beq, "vm_wait_ready");
    implied(p, M::Rts);
    p.label("vm_wait_ready");
    abs(p, M::Lda, ACTION);
    emit(p, M::Cmp, A::Immediate, O::Byte(2));
    branch(p, M::Bne, "vm_wait_done");
    abs(p, M::Lda, CURRENT_INDEX);
    emit(p, M::Cmp, A::Immediate, O::Byte(1));
    branch(p, M::Beq, "vm_wait_target");
    byte(p, M::Lda, 1);
    own(p, M::Sta, 0x41);
    call(p, "battle_refresh_pose");
    p.label("vm_wait_target");
    registers(p);
    byte(p, M::Lda, 1);
    its(p, M::Sta, 0x41);
    its(p, M::Sta, 0x46);
    emit(p, M::Ldy, A::Absolute, O::Word(TARGET));
    call(p, "battle_refresh_pose");
    p.label("vm_wait_done");
    jump(p, "vm_next4");
    p.label("battle_refresh_pose")
        .assume_mode(CpuMode::NATIVE_M8_X16);
    call(p, "battle_shortage");
    call(p, "battle_pose");
    implied(p, M::Rts);
    p.label("battle_pose").assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    own(p, M::Lda, 0x4f);
    word(p, M::And, 0xff);
    abs(p, M::Sta, FACTOR);
    word(p, M::Lda, 9);
    implied(p, M::Sec);
    abs(p, M::Sbc, FACTOR);
    branch(p, M::Bpl, "battle_pose_halve");
    emit(p, M::Eor, A::Immediate, O::Word(0xffff));
    emit(p, M::Inc, A::Accumulator, O::None);
    emit(p, M::Lsr, A::Accumulator, O::None);
    emit(p, M::Eor, A::Immediate, O::Word(0xffff));
    emit(p, M::Inc, A::Accumulator, O::None);
    branch(p, M::Bra, "battle_pose_store");
    p.label("battle_pose_halve")
        .assume_mode(CpuMode::NATIVE_M16_X16);
    emit(p, M::Lsr, A::Accumulator, O::None);
    p.label("battle_pose_store");
    abs(p, M::Sta, FACTOR);
    word(p, M::Lda, 4);
    implied(p, M::Sec);
    abs(p, M::Sbc, FACTOR);
    m8(p);
    own(p, M::Sta, 0x42);
    implied(p, M::Rts);
    p.label("vm_terminal").assume_mode(CpuMode::NATIVE_M8_X16);
    program(p, M::Lda, base, 1);
    abs(p, M::Sta, ACTION);
    call(p, "battle_pair");
    abs(p, M::Lda, ACTION);
    branch(p, M::Bne, "vm_terminal_actor");
    its(p, M::Lda, 0x45);
    branch(p, M::Bmi, "vm_terminal_other_actor");
    jump(p, "vm_next8");
    p.label("vm_terminal_other_actor");
    abs(p, M::Lda, CURRENT_INDEX);
    branch(p, M::Bra, "vm_terminal_poses");
    p.label("vm_terminal_actor");
    own(p, M::Lda, 0x45);
    branch(p, M::Bmi, "vm_terminal_other_target");
    jump(p, "vm_next8");
    p.label("vm_terminal_other_target");
    abs(p, M::Lda, TARGET_INDEX);
    p.label("vm_terminal_poses");
    emit(p, M::Cmp, A::Immediate, O::Byte(2));
    branch(p, M::Bcs, "vm_terminal_enemy");
    pose(p, 0, 0x10, 7);
    pose(p, 2, 0x20, 5);
    jump(p, "vm_branch");
    p.label("vm_terminal_enemy");
    pose(p, 0, 0x20, 5);
    jump(p, "vm_branch");
    p.label("vm_after").assume_mode(CpuMode::NATIVE_M8_X16);
    call(p, "battle_pair");
    call(p, "battle_tick_durations");
    abs(p, M::Stz, ACTION);
    own(p, M::Lda, 0x5a);
    branch(p, M::Beq, "vm_after_next");
    descriptor_message(p, 0, 6);
    byte(p, M::Lda, 1);
    abs(p, M::Sta, ACTION);
    p.label("vm_after_next");
    m16(p);
    abs(p, M::Inc, ORDER_INDEX);
    abs(p, M::Lda, ORDER_INDEX);
    abs(p, M::Cmp, ACTOR_COUNT);
    m8(p);
    branch(p, M::Bcs, "vm_after_round");
    abs(p, M::Lda, ACTION);
    branch(p, M::Beq, "vm_after_branch");
    jump(p, "vm_branch_yield");
    p.label("vm_after_branch");
    jump(p, "vm_branch");
    p.label("vm_after_round");
    abs(p, M::Lda, ACTION);
    branch(p, M::Beq, "vm_after_continue");
    jump(p, "vm_yield8");
    p.label("vm_after_continue");
    jump(p, "vm_next8");
    durations(p);
    p.label("vm_skip").assume_mode(CpuMode::NATIVE_M8_X16);
    call(p, "battle_pair");
    m16(p);
    own(p, M::Lda, 0x2e);
    word(p, M::And, 0x802);
    m8(p);
    branch(p, M::Bne, "vm_skip_held");
    jump(p, "vm_next8");
    p.label("vm_skip_held");
    descriptor_message(p, 0, 7);
    jump(p, "vm_branch_yield");
    message(p, base);
    assess(p);
    p.label("vm_escape").assume_mode(CpuMode::NATIVE_M8_X16);
    program(p, M::Lda, base, 1);
    abs(p, M::Sta, ACTION);
    call(p, "battle_pair");
    abs(p, M::Lda, ACTION);
    branch(p, M::Bne, "vm_escape_target");
    own(p, M::Lda, 0x45);
    byte(p, M::And, 0x04);
    branch(p, M::Beq, "vm_escape_no");
    abs(p, M::Lda, CURRENT_INDEX);
    branch(p, M::Bra, "vm_escape_pose");
    p.label("vm_escape_target");
    its(p, M::Lda, 0x45);
    byte(p, M::And, 0x04);
    branch(p, M::Beq, "vm_escape_no");
    abs(p, M::Lda, TARGET_INDEX);
    p.label("vm_escape_pose");
    emit(p, M::Cmp, A::Immediate, O::Byte(2));
    branch(p, M::Bcs, "vm_escape_enemy");
    pose(p, 0, 0x10, 9);
    jump(p, "vm_branch");
    p.label("vm_escape_enemy");
    pose(p, 2, 0x10, 9);
    jump(p, "vm_branch");
    p.label("vm_escape_no");
    jump(p, "vm_next8");
    p.label("vm_alive").assume_mode(CpuMode::NATIVE_M8_X16);
    call(p, "battle_pair");
    own(p, M::Lda, 0x45);
    its(p, M::Ora, 0x45);
    branch(p, M::Bmi, "vm_alive_ended");
    jump(p, "vm_branch");
    p.label("vm_alive_ended");
    jump(p, "vm_next8");
    p.label("vm_defeat").assume_mode(CpuMode::NATIVE_M8_X16);
    slot(p, M::Lda, 0, 0x45);
    branch(p, M::Bpl, "vm_defeat_no");
    jump(p, "vm_branch");
    p.label("vm_defeat_no");
    jump(p, "vm_next8");
    p.label("vm_keep").assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    slot(p, M::Lda, 0, 4);
    abs(p, M::Sta, STATS + 4);
    slot(p, M::Lda, 0, 8);
    abs(p, M::Sta, STATS + 8);
    m8(p);
    jump(p, "vm_next4");
    p.label("vm_experience").assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    abs(p, M::Lda, STATS + 0x20);
    implied(p, M::Clc);
    slot(p, M::Adc, 2, 0x1e);
    abs(p, M::Sta, STATS + 0x20);
    word(p, M::Lda, 0);
    abs(p, M::Adc, STATS + 0x22);
    abs(p, M::Sta, STATS + 0x22);
    m8(p);
    jump(p, "vm_next4");
    growth_rules(p, thresholds, growth, base);
    p.label("vm_enemy_is").assume_mode(CpuMode::NATIVE_M8_X16);
    abs(p, M::Lda, crate::sfc_encounter::ENEMY);
    program(p, M::Cmp, base, 1);
    branch(p, M::Bne, "vm_enemy_is_not");
    jump(p, "vm_branch");
    p.label("vm_enemy_is_not");
    jump(p, "vm_next8");
    p.label("vm_final").assume_mode(CpuMode::NATIVE_M8_X16);
    slot(p, M::Lda, 2, 1);
    emit(p, M::Cmp, A::Immediate, O::Byte(38));
    branch(p, M::Beq, "vm_final_yes");
    emit(p, M::Cmp, A::Immediate, O::Byte(39));
    branch(p, M::Beq, "vm_final_yes");
    jump(p, "vm_next8");
    p.label("vm_final_yes");
    jump(p, "vm_branch");
    p.label("vm_flag").assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    program(p, M::Lda, base, 2);
    implied(p, M::Pha);
    for _ in 0..3 {
        emit(p, M::Lsr, A::Accumulator, O::None);
    }
    implied(p, M::Tay);
    implied(p, M::Pla);
    emit(p, M::And, A::Immediate, O::Word(7));
    implied(p, M::Tax);
    m8(p);
    emit(p, M::Lda, A::AbsoluteLongX, O::Long(bits));
    emit(
        p,
        M::And,
        A::AbsoluteY,
        O::Word(crate::sfc_field_events::GLOBALS),
    );
    branch(p, M::Beq, "vm_flag_clear");
    jump(p, "vm_branch");
    p.label("vm_flag_clear");
    jump(p, "vm_next8");
    p.label("vm_battle_request")
        .assume_mode(CpuMode::NATIVE_M8_X16);
    program(p, M::Lda, base, 1);
    abs(p, M::Sta, crate::sfc_encounter::ENEMY);
    byte(p, M::Lda, 1);
    abs(p, M::Sta, crate::sfc_encounter::REQUEST);
    jump(p, "vm_next4");
    p.label("vm_clear_arle").assume_mode(CpuMode::NATIVE_M8_X16);
    emit(p, M::Ldx, A::Immediate, O::Word(0));
    p.label("vm_clear_arle_byte");
    emit(p, M::Stz, A::AbsoluteX, O::Word(ACTORS + 0x20));
    implied(p, M::Inx);
    emit(p, M::Cpx, A::Immediate, O::Word(0x48));
    branch(p, M::Bne, "vm_clear_arle_byte");
    jump(p, "vm_next4");
    status(p, base);
    reward(p);
}
