fn advance(p: &mut w65c816::Assembler, n: u16) {
    use crate::sfc::{emit, implied};
    use w65c816::{AddressingMode as A, Mnemonic as M, Operand as O};
    emit(p, M::Rep, A::ImmediateByte, O::Byte(0x20));
    emit(p, M::Lda, A::Absolute, O::Word(SEQUENCE));
    implied(p, M::Clc);
    emit(p, M::Adc, A::Immediate, O::Word(n));
    emit(p, M::Sta, A::Absolute, O::Word(SEQUENCE));
    emit(p, M::Sep, A::ImmediateByte, O::Byte(0x20));
}
fn write_scratch_digits(p: &mut w65c816::Assembler, at: u16) {
    use crate::sfc::{emit, implied};
    use w65c816::{AddressingMode as A, Mnemonic as M, Operand as O};
    emit(p, M::Stz, A::Absolute, O::Word(at + 1));
    let again = format!("b1_menu_tens_{at:x}");
    let done = format!("b1_menu_units_{at:x}");
    p.label(&again);
    emit(p, M::Cmp, A::Immediate, O::Byte(10));
    p.emit_label_ref(M::Bcc, A::Relative8, &done);
    implied(p, M::Sec);
    emit(p, M::Sbc, A::Immediate, O::Byte(10));
    emit(p, M::Inc, A::Absolute, O::Word(at + 1));
    p.emit_label_ref(M::Bra, A::Relative8, &again);
    p.label(&done);
    emit(p, M::Sta, A::Absolute, O::Word(at));
}
