use super::*;
pub(super) fn emit(p: &mut w65c816::Assembler, tables: &Tables) -> Result<()> {
    use crate::sfc::emit;
    let Tables {
        boundary, program, ..
    } = *tables;
    p.label("field_op_03");
    jump(p, "field_goto4");
    p.label("field_op_05");
    abs(p, M::Lda, DEPTH);
    branch(p, M::Bne, "field_return");
    jump(p, "field_end");
    p.label("field_return");
    abs(p, M::Dec, DEPTH);
    m16(p);
    abs(p, M::Lda, DEPTH);
    emit(p, M::And, A::Immediate, O::Word(255));
    emit(p, M::Asl, A::Accumulator, O::None);
    implied(p, M::Tax);
    emit(p, M::Lda, A::AbsoluteX, O::Word(RETURNS));
    abs(p, M::Sta, PC);
    m8(p);
    jump(p, "field_step");
    p.label("field_op_04");
    abs(p, M::Lda, DEPTH);
    emit(p, M::Cmp, A::Immediate, O::Byte(MAX_DEPTH));
    branch(p, M::Bcc, "field_call_room");
    jump(p, "field_end");
    p.label("field_call_room");
    m16(p);
    emit(p, M::And, A::Immediate, O::Word(255));
    emit(p, M::Asl, A::Accumulator, O::None);
    implied(p, M::Tay);
    abs(p, M::Lda, PC);
    implied(p, M::Clc);
    emit(p, M::Adc, A::Immediate, O::Word(8));
    emit(p, M::Sta, A::AbsoluteY, O::Word(RETURNS));
    m8(p);
    abs(p, M::Inc, DEPTH);
    jump(p, "field_goto4");
    p.label("field_op_02");
    m16(p);
    abs(p, M::Lda, WAIT);
    branch(p, M::Bne, "field_wait_count");
    long_x(p, M::Lda, program + 2);
    abs(p, M::Sta, WAIT);
    m8(p);
    implied(p, M::Rts);
    p.label("field_wait_count")
        .assume_mode(CpuMode::NATIVE_M16_X16);
    abs(p, M::Dec, WAIT);
    m8(p);
    branch(p, M::Beq, "field_wait_done");
    implied(p, M::Rts);
    p.label("field_wait_done");
    jump(p, "field_next4");
    p.label("field_op_40");
    abs(p, M::Lda, crate::sfc_b1_map::MAP_EVENT);
    branch(p, M::Bne, "field_redraw");
    abs(p, M::Lda, FADE_LEVEL);
    branch(p, M::Bne, "field_redraw");
    abs(p, M::Lda, 0x50c);
    emit(p, M::Cmp, A::Immediate, O::Byte(boundary));
    branch(p, M::Bcs, "field_redraw");
    call(p, "b1_view_find");
    m16(p);
    abs(p, M::Lda, crate::sfc_floor_walls::BASE);
    emit(p, M::Cmp, A::Immediate, O::Word(0xffff));
    branch(p, M::Beq, "field_redraw_m16");
    abs(p, M::Lda, 0x51a);
    abs(p, M::Cmp, crate::sfc_b1::SHOWN_VIEW);
    branch(p, M::Bne, "field_redraw_m16");
    m8(p);
    jump(p, "field_next4");
    p.label("field_redraw_m16")
        .assume_mode(CpuMode::NATIVE_M16_X16);
    m8(p);
    p.label("field_redraw");
    call(p, "field_picture_view");
    jump(p, "field_next4");
    p.label("field_op_88");
    m16(p);
    long_x(p, M::Lda, program + 2);
    abs(p, M::Sta, PC);
    m8(p);
    long_x(p, M::Lda, program + 1);
    emit(p, M::Inc, A::Accumulator, O::None);
    abs(p, M::Sta, SCENE_REQUEST);
    implied(p, M::Rts);
    p.label("field_op_83");
    long_x(p, M::Lda, program + 1);
    abs(p, M::Sta, crate::sfc_encounter::ENEMY);
    write(p, crate::sfc_encounter::REQUEST, 1);
    jump(p, "field_next4");
    p.label("field_op_8c");
    m16(p);
    abs(p, M::Lda, crate::sfc_battle::HP_MAX);
    abs(p, M::Sta, crate::sfc_battle::HP);
    abs(p, M::Lda, MP_MAX);
    abs(p, M::Sta, MP);
    m8(p);
    call(p, "b1_portrait_select");
    jump(p, "field_next4");
    p.label("field_op_06");
    m16(p);
    long_x(p, M::Lda, program + 4);
    abs(p, M::Cmp, LOOP_TARGET);
    branch(p, M::Beq, "field_loop_count");
    abs(p, M::Sta, LOOP_TARGET);
    long_x(p, M::Lda, program + 2);
    abs(p, M::Sta, LOOP_COUNT);
    m8(p);
    jump(p, "field_step");
    p.label("field_loop_count")
        .assume_mode(CpuMode::NATIVE_M16_X16);
    abs(p, M::Dec, LOOP_COUNT);
    branch(p, M::Beq, "field_loop_done");
    m8(p);
    jump(p, "field_goto4");
    p.label("field_loop_done")
        .assume_mode(CpuMode::NATIVE_M16_X16);
    emit(p, M::Lda, A::Immediate, O::Word(0xffff));
    abs(p, M::Sta, LOOP_TARGET);
    m8(p);
    jump(p, "field_next8");
    Ok(())
}
