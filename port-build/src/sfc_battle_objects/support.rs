use super::*;
pub(super) fn emit_support(p: &mut Assembler, bank_add: u16) {
    p.label("bvm_translate").assume_mode(CpuMode::NATIVE_M8_X16);
    dp(p, M::Stz, VALID);
    m16(p);
    for (i, (start, len, home)) in places().into_iter().enumerate() {
        let skip = format!("bvm_translate_{i}");
        dp(p, M::Lda, TMP);
        implied(p, M::Sec);
        imm16(p, M::Sbc, start as u16);
        dp(p, M::Sta, PTR);
        dp(p, M::Lda, TMP + 2);
        imm16(p, M::Sbc, (start >> 16) as u16);
        br(p, M::Bne, &skip);
        dp(p, M::Lda, PTR);
        imm16(p, M::Cmp, len as u16);
        br(p, M::Bcs, &skip);
        implied(p, M::Clc);
        imm16(p, M::Adc, home);
        dp(p, M::Sta, PTR);
        m8(p);
        imm8(p, M::Lda, 1);
        dp(p, M::Sta, VALID);
        implied(p, M::Rts);
        p.label(skip).assume_mode(CpuMode::NATIVE_M16_X16);
    }
    m8(p);
    implied(p, M::Rts);
    p.label("bvm_bind").assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    ax(p, M::Lda, 0xa8);
    dp(p, M::Cmp, REFSRC);
    br(p, M::Bne, "bvm_bind_new");
    ax(p, M::Lda, 0xaa);
    dp(p, M::Cmp, REFSRC + 2);
    br(p, M::Bne, "bvm_bind_new");
    m8(p);
    implied(p, M::Rts);
    p.label("bvm_bind_new").assume_mode(CpuMode::NATIVE_M16_X16);
    ax(p, M::Lda, 0xa8);
    dp(p, M::Sta, REFSRC);
    dp(p, M::Sta, TMP);
    ax(p, M::Lda, 0xaa);
    dp(p, M::Sta, REFSRC + 2);
    dp(p, M::Sta, TMP + 2);
    m8(p);
    jsr(p, "bvm_translate");
    m16(p);
    dp(p, M::Lda, PTR);
    dp(p, M::Sta, REFBASE);
    m8(p);
    dp(p, M::Lda, VALID);
    dp(p, M::Sta, REFOK);
    dp(p, M::Stz, REFSPLIT);
    m16(p);
    dp(p, M::Lda, REFSRC);
    imm16(p, M::Cmp, 0x47c0);
    br(p, M::Bne, "bvm_bind_done");
    dp(p, M::Lda, REFSRC + 2);
    imm16(p, M::Cmp, 0x004b);
    br(p, M::Bne, "bvm_bind_done");
    m8(p);
    dp(p, M::Inc, REFSPLIT);
    p.label("bvm_bind_done");
    m8(p);
    dp(p, M::Lda, REFSPLIT);
    imm8(p, M::Eor, 1);
    dp(p, M::And, REFOK);
    dp(p, M::Sta, REFFAST);
    dp(p, M::Ldx, OBJ);
    implied(p, M::Rts);
    p.label("bvm_at").assume_mode(CpuMode::NATIVE_M8_X16);
    imm8(p, M::Cmp, 0x80);
    br(p, M::Bne, "bvm_at_not_self");
    m16(p);
    dp(p, M::Lda, OBJ);
    dp(p, M::Sta, PTR);
    dp(p, M::Lda, OFF);
    imm16(p, M::And, 0xff);
    implied(p, M::Tay);
    m8(p);
    imm8(p, M::Lda, 1);
    dp(p, M::Sta, VALID);
    implied(p, M::Rts);
    p.label("bvm_at_not_self");
    imm8(p, M::Cmp, 0x40);
    br(p, M::Bne, "bvm_at_bound");
    m16(p);
    imm16(p, M::Lda, 0x800);
    dp(p, M::Sta, PTR);
    dp(p, M::Lda, OFF);
    imm16(p, M::And, 0xff);
    acc(p, M::Asl);
    acc(p, M::Asl);
    implied(p, M::Tay);
    m8(p);
    imm8(p, M::Lda, 1);
    dp(p, M::Sta, VALID);
    implied(p, M::Rts);
    p.label("bvm_at_bound");
    dp(p, M::Ldx, OBJ);
    jsr(p, "bvm_bind");
    dp(p, M::Lda, REFOK);
    dp(p, M::Sta, VALID);
    m16(p);
    dp(p, M::Lda, REFBASE);
    dp(p, M::Sta, PTR);
    dp(p, M::Lda, OFF);
    imm16(p, M::And, 0xff);
    implied(p, M::Tay);
    m8(p);
    dp(p, M::Lda, REFSPLIT);
    br(p, M::Beq, "bvm_at_done");
    implied(p, M::Tya);
    imm8(p, M::Cmp, 8);
    br(p, M::Bcc, "bvm_at_done");
    m16(p);
    imm16(p, M::Lda, crate::sfc_b1_menu::INVENTORY - 8);
    dp(p, M::Sta, PTR);
    m8(p);
    p.label("bvm_at_done");
    implied(p, M::Rts);
    p.label("bvm_read").assume_mode(CpuMode::NATIVE_M8_X16);
    dp(p, M::Sta, RW);
    m16(p);
    dp(p, M::Stz, TMP + 2);
    dp(p, M::Stz, TMP);
    m8(p);
    dp(p, M::Lda, VALID);
    br(p, M::Beq, "bvm_read_done");
    m16(p);
    emit(p, M::Lda, A::DirectPageIndirectIndexedY, O::Byte(PTR));
    dp(p, M::Sta, TMP);
    m8(p);
    dp(p, M::Lda, RW);
    imm8(p, M::Cmp, 2);
    br(p, M::Beq, "bvm_read_done");
    br(p, M::Bcs, "bvm_read_dword");
    dp(p, M::Stz, TMP + 1);
    br(p, M::Bra, "bvm_read_done");
    p.label("bvm_read_dword");
    implied(p, M::Iny);
    implied(p, M::Iny);
    m16(p);
    emit(p, M::Lda, A::DirectPageIndirectIndexedY, O::Byte(PTR));
    dp(p, M::Sta, TMP + 2);
    m8(p);
    p.label("bvm_read_done");
    dp(p, M::Ldx, OBJ);
    implied(p, M::Rts);
    p.label("bvm_write").assume_mode(CpuMode::NATIVE_M8_X16);
    dp(p, M::Sta, RW);
    dp(p, M::Lda, VALID);
    br(p, M::Beq, "bvm_write_done");
    dp(p, M::Lda, RW);
    imm8(p, M::Cmp, 1);
    br(p, M::Bne, "bvm_write_wide");
    dp(p, M::Lda, RES);
    emit(p, M::Sta, A::DirectPageIndirectIndexedY, O::Byte(PTR));
    br(p, M::Bra, "bvm_write_done");
    p.label("bvm_write_wide");
    m16(p);
    dp(p, M::Lda, RES);
    emit(p, M::Sta, A::DirectPageIndirectIndexedY, O::Byte(PTR));
    m8(p);
    dp(p, M::Lda, RW);
    imm8(p, M::Cmp, 4);
    br(p, M::Bne, "bvm_write_done");
    implied(p, M::Iny);
    implied(p, M::Iny);
    m16(p);
    dp(p, M::Lda, RES + 2);
    emit(p, M::Sta, A::DirectPageIndirectIndexedY, O::Byte(PTR));
    m8(p);
    p.label("bvm_write_done");
    dp(p, M::Ldx, OBJ);
    implied(p, M::Rts);
    p.label("bvm_destination")
        .assume_mode(CpuMode::NATIVE_M8_X16);
    cbyte(p, 2);
    dp(p, M::Sta, OFF);
    dp(p, M::Lda, MODE);
    imm8(p, M::And, 0xc0);
    jsr(p, "bvm_at");
    dp(p, M::Lda, MODE);
    imm8(p, M::And, 0xc0);
    imm8(p, M::Cmp, 0x40);
    br(p, M::Bne, "bvm_destination_width");
    imm8(p, M::Lda, 4);
    implied(p, M::Rts);
    p.label("bvm_destination_width");
    dp(p, M::Lda, WIDTH);
    implied(p, M::Rts);
    p.label("bvm_operands").assume_mode(CpuMode::NATIVE_M8_X16);
    cbyte(p, 1);
    dp(p, M::Sta, MODE);
    jsr(p, "bvm_destination");
    jsr(p, "bvm_read");
    copy32(p, LHS, TMP);
    dp(p, M::Lda, MODE);
    imm8(p, M::And, 0x30);
    br(p, M::Bne, "bvm_operands_place");
    m16(p);
    dp(p, M::Stz, SRC + 2);
    m8(p);
    dp(p, M::Lda, WIDTH);
    imm8(p, M::Cmp, 1);
    br(p, M::Bne, "bvm_operands_wide");
    cbyte(p, 3);
    dp(p, M::Sta, SRC);
    dp(p, M::Stz, SRC + 1);
    implied(p, M::Rts);
    p.label("bvm_operands_wide");
    m16(p);
    cword(p, 4);
    dp(p, M::Sta, SRC);
    m8(p);
    dp(p, M::Lda, WIDTH);
    imm8(p, M::Cmp, 4);
    br(p, M::Bne, "bvm_operands_done");
    m16(p);
    cword(p, 6);
    dp(p, M::Sta, SRC + 2);
    m8(p);
    p.label("bvm_operands_done");
    implied(p, M::Rts);
    p.label("bvm_operands_place");
    acc(p, M::Asl);
    acc(p, M::Asl);
    implied(p, M::Pha);
    cbyte(p, 3);
    dp(p, M::Sta, OFF);
    implied(p, M::Pla);
    implied(p, M::Pha);
    jsr(p, "bvm_at");
    implied(p, M::Pla);
    imm8(p, M::Cmp, 0x40);
    br(p, M::Bne, "bvm_operands_width");
    imm8(p, M::Lda, 4);
    br(p, M::Bra, "bvm_operands_read");
    p.label("bvm_operands_width");
    dp(p, M::Lda, WIDTH);
    p.label("bvm_operands_read");
    jsr(p, "bvm_read");
    copy32(p, SRC, TMP);
    implied(p, M::Rts);
    p.label("bvm_store").assume_mode(CpuMode::NATIVE_M8_X16);
    dp(p, M::Lda, WIDTH);
    imm8(p, M::Cmp, 4);
    br(p, M::Beq, "bvm_store_truncated");
    m16(p);
    dp(p, M::Stz, RES + 2);
    m8(p);
    imm8(p, M::Cmp, 2);
    br(p, M::Beq, "bvm_store_truncated");
    dp(p, M::Stz, RES + 1);
    p.label("bvm_store_truncated");
    jsr(p, "bvm_destination");
    jmp(p, "bvm_write");
    p.label("bvm_arith").assume_mode(CpuMode::NATIVE_M8_X16);
    copy32(p, RES, LHS);
    dp(p, M::Lda, MODE);
    imm8(p, M::And, 15);
    let arith: [(u8, &str); 13] = [
        (0, "bvm_a_set"),
        (1, "bvm_a_add"),
        (2, "bvm_a_sub"),
        (3, "bvm_a_mul"),
        (4, "bvm_a_div"),
        (5, "bvm_a_mod"),
        (6, "bvm_a_and"),
        (7, "bvm_a_or"),
        (8, "bvm_a_xor"),
        (9, "bvm_a_not"),
        (10, "bvm_a_neg"),
        (11, "bvm_a_shl"),
        (12, "bvm_a_shr"),
    ];
    for (n, label) in arith {
        imm8(p, M::Cmp, n);
        let skip = format!("{label}_no");
        br(p, M::Bne, &skip);
        jmp(p, label);
        p.label(skip).assume_mode(CpuMode::NATIVE_M8_X16);
    }
    implied(p, M::Rts);
    p.label("bvm_a_set").assume_mode(CpuMode::NATIVE_M8_X16);
    copy32(p, RES, SRC);
    implied(p, M::Rts);
    for (label, first, carry) in [("bvm_a_add", M::Clc, M::Adc), ("bvm_a_sub", M::Sec, M::Sbc)] {
        p.label(label).assume_mode(CpuMode::NATIVE_M8_X16);
        m16(p);
        dp(p, M::Lda, LHS);
        implied(p, first);
        dp(p, carry, SRC);
        dp(p, M::Sta, RES);
        dp(p, M::Lda, LHS + 2);
        dp(p, carry, SRC + 2);
        dp(p, M::Sta, RES + 2);
        m8(p);
        implied(p, M::Rts);
    }
    for (label, m) in [
        ("bvm_a_and", M::And),
        ("bvm_a_or", M::Ora),
        ("bvm_a_xor", M::Eor),
    ] {
        p.label(label).assume_mode(CpuMode::NATIVE_M8_X16);
        m16(p);
        dp(p, M::Lda, LHS);
        dp(p, m, SRC);
        dp(p, M::Sta, RES);
        dp(p, M::Lda, LHS + 2);
        dp(p, m, SRC + 2);
        dp(p, M::Sta, RES + 2);
        m8(p);
        implied(p, M::Rts);
    }
    p.label("bvm_a_not").assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    dp(p, M::Lda, SRC);
    imm16(p, M::Eor, 0xffff);
    dp(p, M::Sta, RES);
    dp(p, M::Lda, SRC + 2);
    imm16(p, M::Eor, 0xffff);
    dp(p, M::Sta, RES + 2);
    m8(p);
    implied(p, M::Rts);
    p.label("bvm_a_neg").assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    imm16(p, M::Lda, 0);
    implied(p, M::Sec);
    dp(p, M::Sbc, SRC);
    dp(p, M::Sta, RES);
    imm16(p, M::Lda, 0);
    dp(p, M::Sbc, SRC + 2);
    dp(p, M::Sta, RES + 2);
    m8(p);
    implied(p, M::Rts);
    for (label, left) in [("bvm_a_shl", true), ("bvm_a_shr", false)] {
        p.label(label).assume_mode(CpuMode::NATIVE_M8_X16);
        dp(p, M::Lda, SRC);
        imm8(p, M::And, 31);
        implied(p, M::Tay);
        br(p, M::Beq, &format!("{label}_done"));
        m16(p);
        p.label(format!("{label}_bit"));
        if left {
            dp(p, M::Asl, RES);
            dp(p, M::Rol, RES + 2);
        } else {
            dp(p, M::Lsr, RES + 2);
            dp(p, M::Ror, RES);
        }
        implied(p, M::Dey);
        br(p, M::Bne, &format!("{label}_bit"));
        m8(p);
        p.label(format!("{label}_done"));
        implied(p, M::Rts);
    }
    p.label("bvm_a_mul").assume_mode(CpuMode::NATIVE_M8_X16);
    jsr(p, "bvm_multiply");
    implied(p, M::Rts);
    p.label("bvm_multiply").assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    dp(p, M::Lda, SRC);
    br(p, M::Bne, "bvm_multiply_general");
    dp(p, M::Lda, SRC + 2);
    acc(p, M::Dec);
    br(p, M::Bne, "bvm_multiply_general");
    dp(p, M::Stz, RES);
    dp(p, M::Lda, LHS);
    dp(p, M::Sta, RES + 2);
    acc(p, M::Asl);
    implied(p, M::Clv);
    imm16(p, M::Lda, 0);
    dp(p, M::Sta, WORK + 4);
    dp(p, M::Sta, WORK + 6);
    br(p, M::Bra, "bvm_multiply_done");
    p.label("bvm_multiply_general")
        .assume_mode(CpuMode::NATIVE_M16_X16);
    dp(p, M::Stz, RES);
    dp(p, M::Stz, RES + 2);
    dp(p, M::Lda, LHS);
    dp(p, M::Sta, WORK);
    dp(p, M::Lda, LHS + 2);
    dp(p, M::Sta, WORK + 2);
    dp(p, M::Lda, SRC);
    dp(p, M::Sta, WORK + 4);
    dp(p, M::Lda, SRC + 2);
    dp(p, M::Sta, WORK + 6);
    p.label("bvm_multiply_bit");
    dp(p, M::Lda, WORK + 4);
    dp(p, M::Ora, WORK + 6);
    br(p, M::Beq, "bvm_multiply_done");
    dp(p, M::Lsr, WORK + 6);
    dp(p, M::Ror, WORK + 4);
    br(p, M::Bcc, "bvm_multiply_skip");
    dp(p, M::Lda, RES);
    implied(p, M::Clc);
    dp(p, M::Adc, WORK);
    dp(p, M::Sta, RES);
    dp(p, M::Lda, RES + 2);
    dp(p, M::Adc, WORK + 2);
    dp(p, M::Sta, RES + 2);
    p.label("bvm_multiply_skip");
    dp(p, M::Asl, WORK);
    dp(p, M::Rol, WORK + 2);
    br(p, M::Bra, "bvm_multiply_bit");
    p.label("bvm_multiply_done");
    dp(p, M::Stz, WORK);
    dp(p, M::Stz, WORK + 2);
    imm16(p, M::Ldy, 0);
    m8(p);
    implied(p, M::Rts);
    p.label("bvm_divide").assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    dp(p, M::Lda, SRC);
    dp(p, M::Ora, SRC + 2);
    br(p, M::Bne, "bvm_divide_some");
    m8(p);
    abs(p, M::Inc, FAULTS + 3);
    implied(p, M::Sec);
    implied(p, M::Rts);
    p.label("bvm_divide_some")
        .assume_mode(CpuMode::NATIVE_M16_X16);
    dp(p, M::Stz, REM);
    dp(p, M::Stz, REM + 2);
    dp(p, M::Lda, SRC + 1);
    dp(p, M::Ora, SRC + 2);
    br(p, M::Beq, "bvm_divide_byte");
    p.emit_label_ref(M::Jmp, A::Absolute, "bvm_divide_wide");
    p.label("bvm_divide_byte")
        .assume_mode(CpuMode::NATIVE_M16_X16);
    m8(p);
    for i in (0..4u8).rev() {
        dp(p, M::Lda, LHS + i);
        emit(p, M::Sta, A::AbsoluteLong, O::Long(0x4204));
        dp(p, M::Lda, REM);
        emit(p, M::Sta, A::AbsoluteLong, O::Long(0x4205));
        dp(p, M::Lda, SRC);
        emit(p, M::Sta, A::AbsoluteLong, O::Long(0x4206));
        for _ in 0..8 {
            implied(p, M::Nop);
        }
        emit(p, M::Lda, A::AbsoluteLong, O::Long(0x4214));
        dp(p, M::Sta, QUO + i);
        emit(p, M::Lda, A::AbsoluteLong, O::Long(0x4216));
        dp(p, M::Sta, REM);
    }
    imm16(p, M::Ldy, 0);
    implied(p, M::Clc);
    implied(p, M::Rts);
    p.label("bvm_divide_wide")
        .assume_mode(CpuMode::NATIVE_M16_X16);
    dp(p, M::Lda, LHS);
    dp(p, M::Sta, QUO);
    dp(p, M::Lda, LHS + 2);
    dp(p, M::Sta, QUO + 2);
    imm16(p, M::Ldy, 32);
    p.label("bvm_divide_skip");
    dp(p, M::Lda, QUO + 2);
    imm16(p, M::And, 0xff00);
    br(p, M::Bne, "bvm_divide_lead");
    implied(p, M::Tya);
    br(p, M::Beq, "bvm_divide_done");
    implied(p, M::Sec);
    imm16(p, M::Sbc, 8);
    implied(p, M::Tay);
    dp(p, M::Lda, QUO + 1);
    dp(p, M::Sta, QUO + 2);
    dp(p, M::Lda, QUO - 1);
    imm16(p, M::And, 0xff00);
    dp(p, M::Sta, QUO);
    br(p, M::Bra, "bvm_divide_skip");
    p.label("bvm_divide_lead");
    implied(p, M::Phx);
    imm16(p, M::Ldx, 1);
    dp(p, M::Lda, SRC + 2);
    br(p, M::Beq, "bvm_divide_lead_shift");
    implied(p, M::Inx);
    imm16(p, M::And, 0xff00);
    br(p, M::Beq, "bvm_divide_lead_shift");
    implied(p, M::Inx);
    p.label("bvm_divide_lead_shift");
    implied(p, M::Tya);
    br(p, M::Beq, "bvm_divide_lead_done");
    implied(p, M::Sec);
    imm16(p, M::Sbc, 8);
    implied(p, M::Tay);
    dp(p, M::Lda, REM + 1);
    dp(p, M::Sta, REM + 2);
    dp(p, M::Lda, REM - 1);
    dp(p, M::Sta, REM);
    dp(p, M::Lda, QUO + 1);
    dp(p, M::Sta, QUO + 2);
    dp(p, M::Lda, QUO - 1);
    imm16(p, M::And, 0xff00);
    dp(p, M::Sta, QUO);
    implied(p, M::Dex);
    br(p, M::Bne, "bvm_divide_lead_shift");
    p.label("bvm_divide_lead_done");
    implied(p, M::Plx);
    implied(p, M::Tya);
    br(p, M::Beq, "bvm_divide_done");
    p.label("bvm_divide_bit");
    dp(p, M::Asl, QUO);
    dp(p, M::Rol, QUO + 2);
    dp(p, M::Rol, REM);
    dp(p, M::Rol, REM + 2);
    dp(p, M::Lda, REM);
    implied(p, M::Sec);
    dp(p, M::Sbc, SRC);
    dp(p, M::Sta, WORK);
    dp(p, M::Lda, REM + 2);
    dp(p, M::Sbc, SRC + 2);
    br(p, M::Bcc, "bvm_divide_less");
    dp(p, M::Sta, REM + 2);
    dp(p, M::Lda, WORK);
    dp(p, M::Sta, REM);
    dp(p, M::Inc, QUO);
    p.label("bvm_divide_less");
    implied(p, M::Dey);
    br(p, M::Bne, "bvm_divide_bit");
    p.label("bvm_divide_done");
    m8(p);
    implied(p, M::Clc);
    implied(p, M::Rts);
    for (label, from) in [("bvm_a_div", QUO), ("bvm_a_mod", REM)] {
        p.label(label).assume_mode(CpuMode::NATIVE_M8_X16);
        jsr(p, "bvm_divide");
        br(p, M::Bcs, &format!("{label}_fault"));
        copy32(p, RES, from);
        p.label(format!("{label}_fault"));
        implied(p, M::Rts);
    }
    p.label("bvm_compare").assume_mode(CpuMode::NATIVE_M8_X16);
    dp(p, M::Stz, COND);
    m16(p);
    dp(p, M::Lda, LHS);
    implied(p, M::Sec);
    dp(p, M::Sbc, SRC);
    dp(p, M::Sta, WORK);
    dp(p, M::Lda, LHS + 2);
    dp(p, M::Sbc, SRC + 2);
    implied(p, M::Php);
    dp(p, M::Ora, WORK);
    dp(p, M::Sta, WORK);
    implied(p, M::Plp);
    p.assume_mode(CpuMode::NATIVE_M16_X16);
    m8(p);
    imm8(p, M::Lda, 0);
    acc(p, M::Rol);
    dp(p, M::Sta, SIGN);
    imm16(p, M::Ldy, 0);
    m16(p);
    dp(p, M::Lda, WORK);
    m8(p);
    br(p, M::Bne, "bvm_compare_ne");
    imm16(p, M::Ldy, 1);
    p.label("bvm_compare_ne");
    dp(p, M::Sty, WORK + 4);
    dp(p, M::Lda, MODE);
    imm8(p, M::And, 15);
    let rels: [(u8, &str); 10] = [
        (0, "ne"),
        (1, "eq"),
        (2, "gt"),
        (3, "lt"),
        (4, "ge"),
        (5, "le"),
        (6, "and"),
        (7, "or"),
        (8, "ne"),
        (9, "nz"),
    ];
    for (n, rel) in rels {
        imm8(p, M::Cmp, n);
        let skip = format!("bvm_compare_{n}_no");
        br(p, M::Bne, &skip);
        jmp(p, &format!("bvm_rel_{rel}"));
        p.label(skip).assume_mode(CpuMode::NATIVE_M8_X16);
    }
    implied(p, M::Rts);
    let set = |p: &mut Assembler| {
        imm8(p, M::Lda, 1);
        dp(p, M::Sta, COND);
        implied(p, M::Rts);
    };
    p.label("bvm_rel_eq").assume_mode(CpuMode::NATIVE_M8_X16);
    dp(p, M::Lda, WORK + 4);
    dp(p, M::Sta, COND);
    implied(p, M::Rts);
    p.label("bvm_rel_ne").assume_mode(CpuMode::NATIVE_M8_X16);
    dp(p, M::Lda, WORK + 4);
    imm8(p, M::Eor, 1);
    dp(p, M::Sta, COND);
    implied(p, M::Rts);
    p.label("bvm_rel_ge").assume_mode(CpuMode::NATIVE_M8_X16);
    dp(p, M::Lda, SIGN);
    dp(p, M::Sta, COND);
    implied(p, M::Rts);
    p.label("bvm_rel_lt").assume_mode(CpuMode::NATIVE_M8_X16);
    dp(p, M::Lda, SIGN);
    imm8(p, M::Eor, 1);
    dp(p, M::Sta, COND);
    implied(p, M::Rts);
    p.label("bvm_rel_gt").assume_mode(CpuMode::NATIVE_M8_X16);
    dp(p, M::Lda, WORK + 4);
    br(p, M::Bne, "bvm_rel_gt_no");
    dp(p, M::Lda, SIGN);
    dp(p, M::Sta, COND);
    p.label("bvm_rel_gt_no");
    implied(p, M::Rts);
    p.label("bvm_rel_le").assume_mode(CpuMode::NATIVE_M8_X16);
    dp(p, M::Lda, WORK + 4);
    br(p, M::Bne, "bvm_rel_le_yes");
    dp(p, M::Lda, SIGN);
    br(p, M::Bne, "bvm_rel_le_no");
    p.label("bvm_rel_le_yes");
    set(p);
    p.label("bvm_rel_le_no").assume_mode(CpuMode::NATIVE_M8_X16);
    implied(p, M::Rts);
    for (rel, m) in [("and", M::And), ("or", M::Ora)] {
        p.label(format!("bvm_rel_{rel}"))
            .assume_mode(CpuMode::NATIVE_M8_X16);
        m16(p);
        dp(p, M::Lda, LHS);
        dp(p, m, SRC);
        br(p, M::Bne, &format!("bvm_rel_{rel}_yes"));
        dp(p, M::Lda, LHS + 2);
        dp(p, m, SRC + 2);
        br(p, M::Bne, &format!("bvm_rel_{rel}_yes"));
        m8(p);
        implied(p, M::Rts);
        p.label(format!("bvm_rel_{rel}_yes"))
            .assume_mode(CpuMode::NATIVE_M16_X16);
        m8(p);
        set(p);
    }
    p.label("bvm_rel_nz").assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    dp(p, M::Lda, LHS);
    dp(p, M::Ora, LHS + 2);
    m8(p);
    br(p, M::Beq, "bvm_rel_nz_no");
    set(p);
    p.label("bvm_rel_nz_no").assume_mode(CpuMode::NATIVE_M8_X16);
    implied(p, M::Rts);
    p.label("bvm_rom").assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    dp(p, M::Lda, TMP);
    dp(p, M::Sta, ROMP);
    dp(p, M::Lda, TMP + 2);
    implied(p, M::Clc);
    imm16(p, M::Adc, bank_add);
    m8(p);
    dp(p, M::Sta, ROMP + 2);
    implied(p, M::Rts);
}
