use super::*;
pub(super) fn emit_collect(p: &mut Assembler, slots: u32, extents: u32, firsts: u32) {
    use crate::sfc_battle_objects::SENTINELS;
    let collect_pool = |p: &mut Assembler, m, field: u16| {
        emit(p, m, A::AbsoluteX, O::Word(field));
    };
    p.label("battle_display_objects")
        .assume_mode(CpuMode::NATIVE_M8_X16);
    implied(p, M::Phd);
    m16(p);
    crate::sfc_battle_act::abs(p, M::Lda, FRAME_POINTER);
    implied(p, M::Pha);
    m8(p);
    crate::sfc_battle_act::abs(p, M::Lda, FRAME_POINTER + 2);
    implied(p, M::Pha);
    m16(p);
    crate::sfc_battle_act::abs(p, M::Lda, u16::from(RECORD));
    crate::sfc_battle_act::abs(p, M::Sta, FRAME_POINTER);
    m8(p);
    crate::sfc_battle_act::abs(p, M::Lda, u16::from(RECORD) + 2);
    crate::sfc_battle_act::abs(p, M::Sta, FRAME_POINTER + 2);
    m16(p);
    word(p, M::Lda, PAGE);
    implied(p, M::Tcd);
    m8(p);
    implied(p, M::Phb);
    byte(p, M::Lda, 0x7e);
    implied(p, M::Pha);
    implied(p, M::Plb);
    m16(p);
    abs(p, M::Stz, VISIBLE);
    abs(p, M::Stz, CHUNK);
    p.label("bdo_group");
    abs(p, M::Lda, CHUNK);
    for _ in 0..5 {
        emit(p, M::Asl, A::Accumulator, O::None);
    }
    implied(p, M::Clc);
    word(p, M::Adc, SENTINELS);
    abs(p, M::Sta, ROW);
    implied(p, M::Clc);
    word(p, M::Adc, 16);
    abs(p, M::Sta, COLUMN);
    abs(p, M::Lda, ROW);
    implied(p, M::Tax);
    collect_pool(p, M::Lda, 8);
    p.label("bdo_object");
    implied(p, M::Tax);
    abs(p, M::Cmp, COLUMN);
    br(p, M::Bne, "bdo_object_live");
    jmp(p, "bdo_group_done");
    p.label("bdo_object_live");
    collect_pool(p, M::Lda, 2);
    word(p, M::And, 0x6000);
    br(p, M::Bne, "bdo_shown");
    jmp(p, "bdo_next");
    p.label("bdo_shown");
    word(p, M::And, 0x2000);
    br(p, M::Beq, "bdo_keep");
    collect_pool(p, M::Lda, 2);
    word(p, M::And, 0xdfff);
    collect_pool(p, M::Sta, 2);
    p.label("bdo_keep");
    abs(p, M::Lda, VISIBLE);
    word(p, M::Cmp, VISIBLE_MAX);
    br(p, M::Bcs, "bdo_full_next");
    collect_pool(p, M::Lda, 0x22);
    abs(p, M::Sta, AT_Y);
    collect_pool(p, M::Lda, 0x28);
    emit(p, M::Asl, A::Accumulator, O::None);
    emit(p, M::Asl, A::Accumulator, O::None);
    abs(p, M::Sta, AT_X);
    collect_pool(p, M::Lda, 0x2a);
    word(p, M::And, 0x7f);
    implied(p, M::Phx);
    implied(p, M::Tax);
    long_x(p, M::Lda, slots);
    word(p, M::And, 0xff);
    emit(p, M::Asl, A::Accumulator, O::None);
    implied(p, M::Tax);
    long_x(p, M::Lda, firsts);
    implied(p, M::Clc);
    abs(p, M::Adc, AT_X);
    implied(p, M::Tax);
    long_x(p, M::Lda, extents);
    implied(p, M::Clc);
    abs(p, M::Adc, AT_Y);
    implied(p, M::Sec);
    word(p, M::Sbc, LEFT[1] as u16);
    br(p, M::Bmi, "bdo_cull");
    long_x(p, M::Lda, extents + 2);
    implied(p, M::Clc);
    abs(p, M::Adc, AT_Y);
    implied(p, M::Sec);
    word(p, M::Sbc, (LEFT[1] + 240) as u16);
    br(p, M::Bpl, "bdo_cull");
    implied(p, M::Plx);
    word(p, M::Lda, VISIBLE_MAX - 1);
    implied(p, M::Sec);
    abs(p, M::Sbc, VISIBLE);
    emit(p, M::Asl, A::Accumulator, O::None);
    emit(p, M::Asl, A::Accumulator, O::None);
    implied(p, M::Tay);
    collect_pool(p, M::Lda, 0x26);
    word(p, M::Eor, 0x8000);
    emit(p, M::Sta, A::AbsoluteY, O::Word(VISIBLE_LIST as u16));
    implied(p, M::Txa);
    emit(p, M::Sta, A::AbsoluteY, O::Word(VISIBLE_LIST as u16 + 2));
    abs(p, M::Inc, VISIBLE);
    br(p, M::Bra, "bdo_next16");
    p.label("bdo_full_next")
        .assume_mode(CpuMode::NATIVE_M16_X16);
    collect_pool(p, M::Lda, 8);
    implied(p, M::Tax);
    abs(p, M::Cmp, COLUMN);
    br(p, M::Bne, "bdo_full_live");
    jmp(p, "bdo_group_done");
    p.label("bdo_full_live");
    collect_pool(p, M::Lda, 2);
    word(p, M::Bit, 0x2000);
    br(p, M::Beq, "bdo_full_next");
    word(p, M::And, 0xdfff);
    collect_pool(p, M::Sta, 2);
    br(p, M::Bra, "bdo_full_next");
    p.label("bdo_cull").assume_mode(CpuMode::NATIVE_M16_X16);
    implied(p, M::Plx);
    p.label("bdo_next16");
    p.label("bdo_next");
    collect_pool(p, M::Lda, 8);
    jmp(p, "bdo_object");
    p.label("bdo_group_done")
        .assume_mode(CpuMode::NATIVE_M16_X16);
    abs(p, M::Inc, CHUNK);
    abs(p, M::Lda, CHUNK);
    word(p, M::Cmp, 5);
    br(p, M::Bcs, "bdo_reverse");
    jmp(p, "bdo_group");
}
