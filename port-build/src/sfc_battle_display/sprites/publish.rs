use super::*;
pub(super) fn emit_publish(p: &mut Assembler, oam: u16, oam_job: u32) {
    p.label("bdo_finish").assume_mode(CpuMode::NATIVE_M16_X16);
    emit(p, M::Ldx, A::Immediate, O::Word(0));
    p.label("bdo_free");
    m8(p);
    long_x(p, M::Lda, cache(5));
    br(p, M::Bne, "bdo_free_next");
    long_x(p, M::Lda, cache(0));
    br(p, M::Beq, "bdo_free_next");
    long_x(p, M::Lda, cache(2));
    byte(p, M::And, 0xf0);
    long(p, M::Sta, FREED_HASH);
    long_x(p, M::Lda, cache(1));
    implied(p, M::Clc);
    long(p, M::Adc, FREED_HASH);
    long_x(p, M::Eor, cache(0));
    implied(p, M::Phx);
    m16(p);
    word(p, M::And, 0xff);
    implied(p, M::Tax);
    m8(p);
    long_x(p, M::Lda, KEY_COUNTS);
    emit(p, M::Dec, A::Accumulator, O::None);
    long_x(p, M::Sta, KEY_COUNTS);
    implied(p, M::Plx);
    byte(p, M::Lda, 0);
    long_x(p, M::Sta, cache(0));
    long_x(p, M::Lda, cache(2));
    byte(p, M::And, 0x0f);
    abs(p, M::Sta, COUNT);
    long_x(p, M::Lda, cache(4));
    abs(p, M::Sta, HIGH);
    long_x(p, M::Lda, cache(3));
    implied(p, M::Phx);
    m16(p);
    word(p, M::And, 0xff);
    implied(p, M::Tax);
    m8(p);
    jsr(p, "bdo_mask");
    byte(p, M::Eor, 0xff);
    long_x(p, M::And, ROWS_USED);
    long_x(p, M::Sta, ROWS_USED);
    implied(p, M::Plx);
    p.label("bdo_free_next");
    implied(p, M::Inx);
    emit(p, M::Cpx, A::Immediate, O::Word(CACHE_ENTRIES));
    br(p, M::Bcc, "bdo_free");
    m16(p);
    abs(p, M::Ldx, ENTRY);
    m8(p);
    p.label("bdo_hide");
    abs(p, M::Cpx, PREV_END);
    br(p, M::Bcs, "bdo_hidden");
    byte(p, M::Lda, 224);
    emit(p, M::Sta, A::AbsoluteX, O::Word(oam + 1));
    implied(p, M::Inx);
    implied(p, M::Inx);
    implied(p, M::Inx);
    implied(p, M::Inx);
    br(p, M::Bra, "bdo_hide");
    p.label("bdo_hidden");
    m16(p);
    abs(p, M::Lda, ENTRY);
    abs(p, M::Sta, PREV_END);
    abs(p, M::Lda, DESCRIPTORS);
    br(p, M::Beq, "bdo_no_upload");
    abs(p, M::Lda, QUEUE + SPRITE_SLOT * 5 + 3);
    br(p, M::Bne, "bdo_no_upload");
    word(p, M::Lda, UPLOAD_LIST as u16);
    abs(p, M::Sta, QUEUE + SPRITE_SLOT * 5);
    abs(p, M::Lda, DESCRIPTORS);
    abs(p, M::Sta, QUEUE + SPRITE_SLOT * 5 + 3);
    m8(p);
    byte(p, M::Lda, (UPLOAD_LIST >> 16) as u8);
    abs(p, M::Sta, QUEUE + SPRITE_SLOT * 5 + 2);
    p.label("bdo_no_upload");
    m8(p);
    for i in 0..5u32 {
        long(p, M::Lda, oam_job + i);
        abs(p, M::Sta, QUEUE + crate::sfc_b1::MENU_OAM_SLOT + i as u16);
    }
    m16(p);
    abs(p, M::Lda, FRAME_POINTER);
    crate::sfc_battle_act::abs(p, M::Sta, u16::from(RECORD));
    m8(p);
    abs(p, M::Lda, FRAME_POINTER + 2);
    crate::sfc_battle_act::abs(p, M::Sta, u16::from(RECORD) + 2);
    implied(p, M::Pla);
    abs(p, M::Sta, FRAME_POINTER + 2);
    m16(p);
    implied(p, M::Pla);
    abs(p, M::Sta, FRAME_POINTER);
    implied(p, M::Pld);
    m8(p);
    implied(p, M::Rts);
}
