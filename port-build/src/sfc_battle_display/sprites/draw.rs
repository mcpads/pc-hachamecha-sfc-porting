use super::*;
pub(super) fn emit_draw(
    p: &mut Assembler,
    records: u32,
    slots: u32,
    tables: [u32; 4],
    oam: u16,
    single_block: u32,
    arle_effect: u16,
) {
    let [left_x, right_x, table_y, high_bits] = tables;
    p.label("bdo_draw").assume_mode(CpuMode::NATIVE_M16_X16);
    emit(p, M::Ldx, A::Immediate, O::Word(CACHE_ENTRIES - 2));
    word(p, M::Lda, 0);
    p.label("bdo_unuse");
    long_x(p, M::Sta, cache(5));
    implied(p, M::Dex);
    implied(p, M::Dex);
    br(p, M::Bpl, "bdo_unuse");
    abs(p, M::Stz, DESCRIPTORS);
    m8(p);
    emit(p, M::Lda, A::Immediate, O::Byte(0));
    long(p, M::Sta, MEMO_COUNT);
    long(p, M::Sta, MEMO_NEXT);
    long(p, M::Sta, NO_ENTRY);
    emit(p, M::Lda, A::Immediate, O::Byte(9));
    long(p, M::Sta, FIT_FAIL);
    m16(p);
    abs(p, M::Lda, QUEUE + SPRITE_SLOT * 5 + 3);
    br(p, M::Beq, "bdo_upload_free");
    word(p, M::Lda, UPLOAD_MAX);
    abs(p, M::Sta, DESCRIPTORS);
    p.label("bdo_upload_free");
    abs(p, M::Stz, ARLE_SEEN);
    abs(p, M::Lda, crate::sfc_b1_menu::MODE);
    word(p, M::And, 0xff);
    br(p, M::Beq, "bdo_all_entries");
    abs(p, M::Lda, crate::sfc_b1_menu::OAM_USED);
    p.label("bdo_all_entries");
    abs(p, M::Sta, ENTRY);
    abs(p, M::Sta, BODIES_FROM);
    word(p, M::Lda, 0xaaaa);
    for k in 0..16 {
        abs(p, M::Sta, oam + 512 + 2 * k);
    }
    abs(p, M::Lda, ENTRY);
    br(p, M::Beq, "bdo_high_done");
    for _ in 0..4 {
        emit(p, M::Lsr, A::Accumulator, O::None);
    }
    implied(p, M::Tax);
    m8(p);
    p.label("bdo_menu_high_clear");
    implied(p, M::Dex);
    emit(p, M::Stz, A::AbsoluteX, O::Word(oam + 512));
    br(p, M::Bne, "bdo_menu_high_clear");
    m16(p);
    p.label("bdo_high_done");
    abs(p, M::Stz, INDEX);
    p.label("bdo_each");
    abs(p, M::Lda, INDEX);
    abs(p, M::Cmp, VISIBLE);
    br(p, M::Bcc, "bdo_each_take");
    jmp(p, "bdo_finish");
    p.label("bdo_each_take");
    emit(p, M::Asl, A::Accumulator, O::None);
    emit(p, M::Asl, A::Accumulator, O::None);
    implied(p, M::Tax);
    long_x(p, M::Lda, VISIBLE_LIST + 2);
    abs(p, M::Sta, OBJECT);
    implied(p, M::Tax);
    pool(p, M::Lda, 0x28);
    abs(p, M::Sta, SHEET_FRAME);
    pool(p, M::Lda, 0x2a);
    word(p, M::And, 0xff);
    word(p, M::Cmp, 128);
    br(p, M::Bcc, "bdo_near_2");
    jmp(p, "bdo_skip");
    p.label("bdo_near_2");
    implied(p, M::Tax);
    long_x(p, M::Lda, slots);
    word(p, M::And, 0xff);
    br(p, M::Bne, "bdo_near_3");
    jmp(p, "bdo_skip");
    p.label("bdo_near_3");
    emit(p, M::Dec, A::Accumulator, O::None);
    abs(p, M::Sta, RESOURCE);
    br(p, M::Bne, "bdo_position");
    abs(p, M::Lda, SHEET_FRAME);
    word(p, M::Cmp, arle_effects::FIRST_FRAME);
    br(p, M::Bcc, "bdo_arle_body");
    word(p, M::Cmp, arle_effects::END_FRAME);
    br(p, M::Bcs, "bdo_arle_body");
    implied(p, M::Sec);
    word(p, M::Sbc, arle_effects::FIRST_FRAME);
    abs(p, M::Sta, SHEET_FRAME);
    word(p, M::Lda, arle_effect);
    abs(p, M::Sta, RESOURCE);
    br(p, M::Bra, "bdo_position");
    p.label("bdo_arle_body");
    m8(p);
    abs(p, M::Lda, ARLE_SEEN);
    br(p, M::Beq, "bdo_position16");
    m16(p);
    jsr(p, "bdo_record");
    p.assume_mode(CpuMode::NATIVE_M8_X16);
    jmp(p, "bdo_skip8");
    p.label("bdo_position16")
        .assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    p.label("bdo_position").assume_mode(CpuMode::NATIVE_M16_X16);
    abs(p, M::Ldx, OBJECT);
    for (field, to) in [(0x1cu16, ORIGIN_X), (0x20, ORIGIN_Y)] {
        let positive = format!("bdo_pos_{field:02x}");
        pool(p, M::Lda, field + 2);
        br(p, M::Bpl, &positive);
        pool(p, M::Lda, field);
        word(p, M::Cmp, 1);
        pool(p, M::Lda, field + 2);
        word(p, M::Adc, 0);
        p.label(&positive);
        abs(p, M::Sta, to);
    }
    pool(p, M::Lda, 0x2c);
    word(p, M::And, 7);
    word(p, M::Cmp, 1);
    br(p, M::Beq, "bdo_right");
    word(p, M::Cmp, 2);
    br(p, M::Beq, "bdo_left");
    abs(p, M::Lda, ORIGIN_X);
    word(p, M::Cmp, 320);
    br(p, M::Bpl, "bdo_right");
    p.label("bdo_left");
    word(p, M::Lda, (LEFT[2] + 256 - 16) as u16);
    abs(p, M::Sta, PANEL_LEFT);
    word(p, M::Lda, (LEFT[2] + 104 + 256) as u16);
    abs(p, M::Sta, PANEL_RIGHT);
    word(p, M::Lda, 0);
    br(p, M::Bra, "bdo_map");
    p.label("bdo_right");
    word(p, M::Lda, (RIGHT[2] + 256 - 16) as u16);
    abs(p, M::Sta, PANEL_LEFT);
    word(p, M::Lda, (RIGHT[2] + 104 + 256) as u16);
    abs(p, M::Sta, PANEL_RIGHT);
    word(p, M::Lda, 1);
    p.label("bdo_map");
    abs(p, M::Sta, CELL);
    for (to, which) in [(ORIGIN_X, 0), (ORIGIN_Y, 1)] {
        let clamp_low = format!("bdo_clamp_{which}_low");
        let clamp_high = format!("bdo_clamp_{which}_high");
        let index = format!("bdo_index_{which}");
        abs(p, M::Lda, to);
        implied(p, M::Clc);
        word(p, M::Adc, (-COORD_FIRST) as u16);
        br(p, M::Bpl, &clamp_low);
        word(p, M::Lda, 0);
        p.label(&clamp_low);
        word(p, M::Cmp, COORDS as u16);
        br(p, M::Bcc, &clamp_high);
        word(p, M::Lda, COORDS as u16 - 1);
        p.label(&clamp_high);
        emit(p, M::Asl, A::Accumulator, O::None);
        implied(p, M::Tax);
        if which == 0 {
            abs(p, M::Lda, CELL);
            br(p, M::Bne, &index);
            long_x(p, M::Lda, left_x);
            br(p, M::Bra, &format!("{index}_done"));
            p.label(&index);
            long_x(p, M::Lda, right_x);
            p.label(format!("{index}_done"));
        } else {
            long_x(p, M::Lda, table_y);
        }
        abs(p, M::Sta, to);
    }
    jsr(p, "bdo_record");
    p.assume_mode(CpuMode::NATIVE_M8_X16);
    abs(p, M::Lda, ATTRIBUTE);
    br(p, M::Beq, "bdo_sprite");
    abs(p, M::Lda, ARLE_SEEN);
    br(p, M::Bne, "bdo_skip8");
    abs(p, M::Inc, ARLE_SEEN);
    m16(p);
    emit(p, M::Lda, A::DirectPage, O::Byte(FRAME_DP));
    implied(p, M::Sec);
    word(p, M::Sbc, records as u16);
    abs(p, M::Sta, ARLE_FRAME);
    abs(p, M::Lda, ORIGIN_X);
    abs(p, M::Sta, ARLE_X);
    abs(p, M::Lda, ORIGIN_Y);
    abs(p, M::Sta, ARLE_Y);
    p.label("bdo_skip");
    m16(p);
    abs(p, M::Inc, INDEX);
    jmp(p, "bdo_each");
    p.label("bdo_skip8").assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    abs(p, M::Inc, INDEX);
    jmp(p, "bdo_each");
    p.label("bdo_sprite").assume_mode(CpuMode::NATIVE_M8_X16);
    emit(p, M::Jsl, A::AbsoluteLong, O::Long(single_block));
    br(p, M::Bcc, "bdo_sprite_general");
    jmp(p, "bdo_skip8");
    p.label("bdo_sprite_general");
    abs(p, M::Stz, MISSED);
    abs(p, M::Stz, FIND_ONLY);
    jsr(p, "bdo_place");
    m16(p);
    for at in [ORIGIN_X, ORIGIN_Y] {
        abs(p, M::Lda, at);
        implied(p, M::Clc);
        word(p, M::Adc, 128);
        abs(p, M::Sta, at);
    }
    abs(p, M::Lda, OBJECT);
    implied(p, M::Sec);
    word(p, M::Sbc, crate::sfc_battle_objects::POOL);
    for _ in 0..3 {
        emit(p, M::Lsr, A::Accumulator, O::None);
    }
    implied(p, M::Tax);
    m8(p);
    abs(p, M::Lda, MISSED);
    br(p, M::Beq, "bdo_sprite_ready");
    m16(p);
    long_x(p, M::Lda, LAST_DRAWN + 2);
    br(p, M::Bne, "bdo_sprite_last");
    m8(p);
    jmp(p, "bdo_skip8");
    p.label("bdo_sprite_last")
        .assume_mode(CpuMode::NATIVE_M16_X16);
    emit(p, M::Dec, A::Accumulator, O::None);
    abs(p, M::Cmp, RESOURCE);
    br(p, M::Beq, "bdo_sprite_same");
    m8(p);
    jmp(p, "bdo_skip8");
    p.label("bdo_sprite_same")
        .assume_mode(CpuMode::NATIVE_M16_X16);
    long_x(p, M::Lda, LAST_DRAWN);
    abs(p, M::Sta, SHEET_FRAME);
    jsr(p, "bdo_record");
    p.assume_mode(CpuMode::NATIVE_M8_X16);
    br(p, M::Bra, "bdo_sprite_draw");
    p.label("bdo_sprite_ready")
        .assume_mode(CpuMode::NATIVE_M8_X16);
    m16(p);
    abs(p, M::Lda, SHEET_FRAME);
    long_x(p, M::Sta, LAST_DRAWN);
    abs(p, M::Lda, RESOURCE);
    emit(p, M::Inc, A::Accumulator, O::None);
    long_x(p, M::Sta, LAST_DRAWN + 2);
    m8(p);
    p.label("bdo_sprite_draw")
        .assume_mode(CpuMode::NATIVE_M8_X16);
    byte(p, M::Lda, 1);
    abs(p, M::Sta, FIND_ONLY);
    emit(p, M::Ldy, A::Immediate, O::Word(0));
    indirect(p, M::Lda);
    abs(p, M::Sta, BLOCKS + 1);
    abs(p, M::Stz, CHUNK);
    emit(p, M::Ldy, A::Immediate, O::Word(1));
    p.label("bdo_chunk");
    abs(p, M::Lda, CHUNK);
    abs(p, M::Cmp, BLOCKS + 1);
    br(p, M::Bcc, "bdo_chunk_take");
    m16(p);
    abs(p, M::Inc, INDEX);
    jmp(p, "bdo_each");
    p.label("bdo_chunk_take")
        .assume_mode(CpuMode::NATIVE_M8_X16);
    indirect(p, M::Lda);
    implied(p, M::Pha);
    byte(p, M::And, 0x80);
    for _ in 0..6 {
        emit(p, M::Lsr, A::Accumulator, O::None);
    }
    abs(p, M::Sta, CHUNK_ATTRIBUTE);
    implied(p, M::Pla);
    byte(p, M::And, 0x7f);
    abs(p, M::Sta, BLOCKS);
    abs(p, M::Lda, MISSED);
    br(p, M::Beq, "bdo_chunk_placed");
    implied(p, M::Phy);
    jsr(p, "bdo_cache");
    implied(p, M::Ply);
    br(p, M::Bra, "bdo_chunk_named");
    p.label("bdo_chunk_placed");
    m16(p);
    abs(p, M::Lda, CHUNK);
    word(p, M::And, 0xff);
    emit(p, M::Asl, A::Accumulator, O::None);
    implied(p, M::Tax);
    emit(p, M::Lda, A::AbsoluteX, O::Word(CHUNK_NAMES));
    abs(p, M::Sta, SLOT_FOUND);
    m8(p);
    p.label("bdo_chunk_named");
    m16(p);
    implied(p, M::Tya);
    implied(p, M::Clc);
    word(p, M::Adc, 7);
    implied(p, M::Tay);
    abs(p, M::Lda, SLOT_FOUND);
    emit(p, M::Inc, A::Accumulator, O::None);
    br(p, M::Bne, "bdo_chunk_blocks");
    abs(p, M::Lda, BLOCKS);
    word(p, M::And, 0xff);
    emit(p, M::Asl, A::Accumulator, O::None);
    abs(p, M::Sta, CELL);
    implied(p, M::Tya);
    implied(p, M::Clc);
    abs(p, M::Adc, CELL);
    implied(p, M::Tay);
    m8(p);
    abs(p, M::Inc, CHUNK);
    jmp(p, "bdo_chunk");
    p.label("bdo_chunk_blocks");
    m8(p);
    abs(p, M::Lda, ARLE_SEEN);
    br(p, M::Beq, "bdo_in_front");
    abs(p, M::Lda, ATTRIBUTE + 1);
    byte(p, M::And, 0xcf);
    byte(p, M::Ora, 0x10);
    br(p, M::Bra, "bdo_priority");
    p.label("bdo_in_front");
    abs(p, M::Lda, ATTRIBUTE + 1);
    p.label("bdo_priority");
    implied(p, M::Clc);
    abs(p, M::Adc, CHUNK_ATTRIBUTE);
    abs(p, M::Sta, CHUNK_ATTRIBUTE);
    abs(p, M::Stz, HIGH);
    p.label("bdo_block");
    abs(p, M::Lda, HIGH);
    abs(p, M::Cmp, BLOCKS);
    br(p, M::Bcc, "bdo_block_take");
    abs(p, M::Inc, CHUNK);
    jmp(p, "bdo_chunk");
    p.label("bdo_block_take");
    m16(p);
    indirect(p, M::Lda);
    word(p, M::And, 0xff);
    implied(p, M::Clc);
    abs(p, M::Adc, ORIGIN_X);
    abs(p, M::Sta, AT_X);
    implied(p, M::Iny);
    indirect(p, M::Lda);
    word(p, M::And, 0xff);
    implied(p, M::Clc);
    abs(p, M::Adc, ORIGIN_Y);
    abs(p, M::Sta, AT_Y);
    implied(p, M::Iny);
    abs(p, M::Lda, ENTRY);
    word(p, M::Cmp, 512);
    br(p, M::Bcs, "bdo_block_clipped");
    abs(p, M::Lda, AT_X);
    abs(p, M::Cmp, PANEL_LEFT);
    br(p, M::Bcc, "bdo_block_clipped");
    br(p, M::Beq, "bdo_block_clipped");
    abs(p, M::Cmp, PANEL_RIGHT);
    br(p, M::Bcs, "bdo_block_clipped");
    abs(p, M::Lda, AT_Y);
    word(p, M::Cmp, (SPRITE_TOP - 16 + 256 + 1) as u16);
    br(p, M::Bcc, "bdo_block_clipped");
    word(p, M::Cmp, (SPRITE_BOTTOM + 256) as u16);
    br(p, M::Bcc, "bdo_hop_7");
    p.label("bdo_block_clipped");
    jmp(p, "bdo_block_next");
    p.label("bdo_hop_7");
    abs(p, M::Ldx, ENTRY);
    m8(p);
    abs(p, M::Lda, AT_X);
    emit(p, M::Sta, A::AbsoluteX, O::Word(oam));
    abs(p, M::Lda, AT_Y);
    emit(p, M::Sta, A::AbsoluteX, O::Word(oam + 1));
    abs(p, M::Lda, HIGH);
    emit(p, M::Asl, A::Accumulator, O::None);
    implied(p, M::Clc);
    abs(p, M::Adc, SLOT_FOUND);
    emit(p, M::Sta, A::AbsoluteX, O::Word(oam + 2));
    abs(p, M::Lda, CHUNK_ATTRIBUTE);
    emit(p, M::Sta, A::AbsoluteX, O::Word(oam + 3));
    abs(p, M::Lda, AT_X + 1);
    emit(p, M::Lsr, A::Accumulator, O::None);
    br(p, M::Bcs, "bdo_high_next");
    m16(p);
    abs(p, M::Lda, ENTRY);
    word(p, M::And, 0x0c);
    emit(p, M::Lsr, A::Accumulator, O::None);
    abs(p, M::Sta, CELL);
    implied(p, M::Tax);
    m8(p);
    long_x(p, M::Lda, high_bits);
    abs(p, M::Sta, CELL);
    m16(p);
    abs(p, M::Lda, ENTRY);
    for _ in 0..4 {
        emit(p, M::Lsr, A::Accumulator, O::None);
    }
    implied(p, M::Tax);
    m8(p);
    p.label("bdo_high_set");
    emit(p, M::Lda, A::AbsoluteX, O::Word(oam + 512));
    abs(p, M::Ora, CELL);
    emit(p, M::Sta, A::AbsoluteX, O::Word(oam + 512));
    p.label("bdo_high_next");
    m16(p);
    abs(p, M::Lda, ENTRY);
    implied(p, M::Clc);
    word(p, M::Adc, 4);
    abs(p, M::Sta, ENTRY);
    p.label("bdo_block_next");
    m8(p);
    abs(p, M::Inc, HIGH);
    jmp(p, "bdo_block");
}
