use super::*;
fn column_masks() -> Vec<u8> {
    (0..256u32)
        .map(|i| {
            let (count, column) = (i >> 4, i & 15);
            let turns = if count == 0 { 0x10000 } else { count };
            let ones = (0..turns.min(8)).fold(0u32, |a, _| (a << 1 | 1) & 0xff);
            ((ones << column) & 0xff) as u8
        })
        .collect()
}
pub(super) fn emit_tile_cache(p: &mut Assembler, records: u32, stages: u32, gather: u32) {
    p.label("bdo_record").assume_mode(CpuMode::NATIVE_M16_X16);
    abs(p, M::Lda, RESOURCE);
    emit(p, M::Asl, A::Accumulator, O::None);
    emit(p, M::Asl, A::Accumulator, O::None);
    implied(p, M::Tax);
    long_x(p, M::Lda, records + 2);
    abs(p, M::Sta, ATTRIBUTE);
    long_x(p, M::Lda, records);
    abs(p, M::Sta, DATA);
    abs(p, M::Lda, SHEET_FRAME);
    emit(p, M::Asl, A::Accumulator, O::None);
    implied(p, M::Clc);
    abs(p, M::Adc, DATA);
    implied(p, M::Tax);
    long_x(p, M::Lda, records);
    implied(p, M::Clc);
    word(p, M::Adc, records as u16);
    emit(p, M::Sta, A::DirectPage, O::Byte(FRAME_DP));
    m8(p);
    byte(p, M::Lda, (records >> 16) as u8);
    emit(p, M::Sta, A::DirectPage, O::Byte(FRAME_DP + 2));
    implied(p, M::Rts);
    p.label("bdo_place").assume_mode(CpuMode::NATIVE_M8_X16);
    emit(p, M::Ldy, A::Immediate, O::Word(0));
    indirect(p, M::Lda);
    abs(p, M::Sta, BLOCKS + 1);
    abs(p, M::Stz, CHUNK);
    emit(p, M::Ldy, A::Immediate, O::Word(1));
    p.label("bdo_place_chunk");
    abs(p, M::Lda, CHUNK);
    abs(p, M::Cmp, BLOCKS + 1);
    br(p, M::Bcc, "bdo_place_take");
    implied(p, M::Rts);
    p.label("bdo_place_take");
    indirect(p, M::Lda);
    byte(p, M::And, 0x7f);
    abs(p, M::Sta, BLOCKS);
    implied(p, M::Phy);
    jsr(p, "bdo_cache");
    implied(p, M::Ply);
    m16(p);
    abs(p, M::Lda, CHUNK);
    word(p, M::And, 0xff);
    emit(p, M::Asl, A::Accumulator, O::None);
    implied(p, M::Tax);
    abs(p, M::Lda, SLOT_FOUND);
    emit(p, M::Sta, A::AbsoluteX, O::Word(CHUNK_NAMES));
    m8(p);
    abs(p, M::Lda, SLOT_FOUND + 1);
    byte(p, M::Cmp, 0xff);
    br(p, M::Bne, "bdo_place_found");
    abs(p, M::Sta, MISSED);
    p.label("bdo_place_found");
    m16(p);
    abs(p, M::Lda, BLOCKS);
    word(p, M::And, 0xff);
    emit(p, M::Asl, A::Accumulator, O::None);
    implied(p, M::Clc);
    word(p, M::Adc, 7);
    abs(p, M::Sta, CELL);
    implied(p, M::Tya);
    implied(p, M::Clc);
    abs(p, M::Adc, CELL);
    implied(p, M::Tay);
    m8(p);
    abs(p, M::Inc, CHUNK);
    br(p, M::Bra, "bdo_place_chunk");
    p.label("bdo_mask").assume_mode(CpuMode::NATIVE_M8_X16);
    implied(p, M::Phx);
    abs(p, M::Lda, COUNT);
    for _ in 0..4 {
        emit(p, M::Asl, A::Accumulator, O::None);
    }
    abs(p, M::Ora, HIGH);
    m16(p);
    word(p, M::And, 0xff);
    implied(p, M::Tax);
    m8(p);
    p.emit_label_ref(M::Lda, A::AbsoluteLongX, "bdo_masks");
    implied(p, M::Plx);
    implied(p, M::Rts);
    p.label("bdo_masks");
    p.data(column_masks());
    p.label("bdo_cache").assume_mode(CpuMode::NATIVE_M8_X16);
    byte(p, M::Lda, 0);
    long(p, M::Sta, KNOWN);
    abs(p, M::Lda, RESOURCE);
    emit(p, M::Inc, A::Accumulator, O::None);
    abs(p, M::Sta, DATA);
    abs(p, M::Lda, CHUNK);
    for _ in 0..4 {
        emit(p, M::Asl, A::Accumulator, O::None);
    }
    abs(p, M::Sta, DATA + 1);
    abs(p, M::Lda, SHEET_FRAME);
    implied(p, M::Clc);
    abs(p, M::Adc, DATA + 1);
    abs(p, M::Eor, DATA);
    abs(p, M::Sta, HASH);
    abs(p, M::Stz, HASH + 1);
    abs(p, M::Ldx, HASH);
    long_x(p, M::Lda, HINTS);
    byte(p, M::Cmp, CACHE_ENTRIES as u8);
    br(p, M::Bcs, "bdo_cache_search");
    abs(p, M::Sta, CELL);
    abs(p, M::Stz, CELL + 1);
    abs(p, M::Ldx, CELL);
    long_x(p, M::Lda, cache(0));
    abs(p, M::Cmp, DATA);
    br(p, M::Bne, "bdo_cache_search");
    long_x(p, M::Lda, cache(1));
    abs(p, M::Cmp, SHEET_FRAME);
    br(p, M::Bne, "bdo_cache_search");
    long_x(p, M::Lda, cache(2));
    byte(p, M::And, 0xf0);
    abs(p, M::Cmp, DATA + 1);
    br(p, M::Beq, "bdo_cache_hit");
    p.label("bdo_cache_search");
    long(p, M::Lda, MEMO_COUNT);
    br(p, M::Beq, "bdo_cache_scan");
    m16(p);
    word(p, M::And, 0xff);
    implied(p, M::Tax);
    m8(p);
    p.label("bdo_cache_memo");
    implied(p, M::Dex);
    long_x(p, M::Lda, MEMO_RESOURCE);
    abs(p, M::Cmp, DATA);
    br(p, M::Bne, "bdo_cache_memo_next");
    long_x(p, M::Lda, MEMO_FRAME);
    abs(p, M::Cmp, SHEET_FRAME);
    br(p, M::Bne, "bdo_cache_memo_next");
    long_x(p, M::Lda, MEMO_CHUNK);
    abs(p, M::Cmp, DATA + 1);
    br(p, M::Bne, "bdo_cache_memo_next");
    abs(p, M::Lda, FIND_ONLY);
    br(p, M::Beq, "bdo_cache_memo_place");
    jmp(p, "bdo_cache_none");
    p.label("bdo_cache_memo_place");
    byte(p, M::Lda, 1);
    long(p, M::Sta, KNOWN);
    jmp(p, "bdo_cache_placing");
    p.label("bdo_cache_memo_next");
    emit(p, M::Cpx, A::Immediate, O::Word(0));
    br(p, M::Bne, "bdo_cache_memo");
    p.label("bdo_cache_scan");
    abs(p, M::Ldx, HASH);
    long_x(p, M::Lda, KEY_COUNTS);
    br(p, M::Bne, "bdo_cache_scan_all");
    jmp(p, "bdo_cache_missing");
    p.label("bdo_cache_scan_all");
    emit(p, M::Ldx, A::Immediate, O::Word(0));
    p.label("bdo_cache_find");
    long_x(p, M::Lda, cache(0));
    abs(p, M::Cmp, DATA);
    br(p, M::Beq, "bdo_cache_key");
    p.label("bdo_cache_next");
    implied(p, M::Inx);
    emit(p, M::Cpx, A::Immediate, O::Word(CACHE_ENTRIES));
    br(p, M::Bcc, "bdo_cache_find");
    br(p, M::Bra, "bdo_cache_missing");
    p.label("bdo_cache_key");
    long_x(p, M::Lda, cache(1));
    abs(p, M::Cmp, SHEET_FRAME);
    br(p, M::Bne, "bdo_cache_next");
    long_x(p, M::Lda, cache(2));
    byte(p, M::And, 0xf0);
    abs(p, M::Cmp, DATA + 1);
    br(p, M::Bne, "bdo_cache_next");
    implied(p, M::Txa);
    implied(p, M::Phx);
    abs(p, M::Ldx, HASH);
    long_x(p, M::Sta, HINTS);
    implied(p, M::Plx);
    p.label("bdo_cache_hit");
    byte(p, M::Lda, 1);
    long_x(p, M::Sta, cache(5));
    jmp(p, "bdo_cache_name");
    p.label("bdo_cache_missing");
    abs(p, M::Lda, FIND_ONLY);
    br(p, M::Beq, "bdo_cache_placing");
    jmp(p, "bdo_cache_fail");
    p.label("bdo_cache_placing");
    m16(p);
    abs(p, M::Lda, DESCRIPTORS);
    word(p, M::Cmp, UPLOAD_MAX - 1);
    m8(p);
    br(p, M::Bcc, "bdo_cache_room");
    jmp(p, "bdo_cache_fail");
    p.label("bdo_cache_room");
    long(p, M::Lda, NO_ENTRY);
    br(p, M::Beq, "bdo_cache_entries");
    jmp(p, "bdo_cache_fail");
    p.label("bdo_cache_entries");
    emit(p, M::Ldx, A::Immediate, O::Word(0));
    p.label("bdo_cache_free");
    long_x(p, M::Lda, cache(0));
    br(p, M::Beq, "bdo_cache_entry");
    implied(p, M::Inx);
    emit(p, M::Cpx, A::Immediate, O::Word(CACHE_ENTRIES));
    br(p, M::Bcc, "bdo_cache_free");
    byte(p, M::Lda, 1);
    long(p, M::Sta, NO_ENTRY);
    jmp(p, "bdo_cache_fail");
    p.label("bdo_cache_entry");
    abs(p, M::Stx, CELL);
    abs(p, M::Lda, BLOCKS);
    long(p, M::Cmp, FIT_FAIL);
    br(p, M::Bcc, "bdo_cache_fit");
    jmp(p, "bdo_cache_fail");
    p.label("bdo_cache_fit");
    const BASE_MASK: u16 = AT_X;
    const SHIFTED_MASK: u16 = AT_X + 1;
    abs(p, M::Lda, BLOCKS);
    abs(p, M::Sta, COUNT);
    abs(p, M::Stz, HIGH);
    jsr(p, "bdo_mask");
    abs(p, M::Sta, BASE_MASK);
    abs(p, M::Stz, ROW);
    emit(p, M::Ldx, A::Immediate, O::Word(0));
    p.label("bdo_fit_row");
    abs(p, M::Stz, HIGH);
    abs(p, M::Lda, BASE_MASK);
    abs(p, M::Sta, SHIFTED_MASK);
    p.label("bdo_fit_column");
    abs(p, M::Lda, HIGH);
    implied(p, M::Clc);
    abs(p, M::Adc, BLOCKS);
    byte(p, M::Cmp, 9);
    br(p, M::Bcs, "bdo_fit_next_row");
    abs(p, M::Lda, SHIFTED_MASK);
    long_x(p, M::And, ROWS_USED);
    br(p, M::Beq, "bdo_fit_found");
    abs(p, M::Asl, SHIFTED_MASK);
    abs(p, M::Inc, HIGH);
    br(p, M::Bra, "bdo_fit_column");
    p.label("bdo_fit_next_row");
    abs(p, M::Inc, ROW);
    implied(p, M::Inx);
    emit(p, M::Cpx, A::Immediate, O::Word(ROWS));
    br(p, M::Bcc, "bdo_fit_row");
    implied(p, M::Dex);
    abs(p, M::Lda, BLOCKS);
    long(p, M::Sta, FIT_FAIL);
    jmp(p, "bdo_cache_fail");
    p.label("bdo_fit_found");
    implied(p, M::Pha);
    byte(p, M::Lda, 0);
    long(p, M::Sta, MEMO_COUNT);
    long(p, M::Sta, MEMO_NEXT);
    implied(p, M::Pla);
    jsr(p, "bdo_mask");
    long_x(p, M::Ora, ROWS_USED);
    long_x(p, M::Sta, ROWS_USED);
    abs(p, M::Lda, CELL);
    abs(p, M::Ldx, HASH);
    long_x(p, M::Sta, HINTS);
    long_x(p, M::Lda, KEY_COUNTS);
    emit(p, M::Inc, A::Accumulator, O::None);
    long_x(p, M::Sta, KEY_COUNTS);
    abs(p, M::Ldx, CELL);
    abs(p, M::Lda, RESOURCE);
    emit(p, M::Inc, A::Accumulator, O::None);
    long_x(p, M::Sta, cache(0));
    abs(p, M::Lda, SHEET_FRAME);
    long_x(p, M::Sta, cache(1));
    abs(p, M::Lda, CHUNK);
    for _ in 0..4 {
        emit(p, M::Asl, A::Accumulator, O::None);
    }
    abs(p, M::Ora, BLOCKS);
    long_x(p, M::Sta, cache(2));
    abs(p, M::Lda, ROW);
    long_x(p, M::Sta, cache(3));
    abs(p, M::Lda, HIGH);
    long_x(p, M::Sta, cache(4));
    byte(p, M::Lda, 1);
    long_x(p, M::Sta, cache(5));
    m16(p);
    abs(p, M::Lda, ROW);
    word(p, M::And, 0xff);
    for _ in 0..10 {
        emit(p, M::Asl, A::Accumulator, O::None);
    }
    abs(p, M::Sta, DATA);
    abs(p, M::Lda, HIGH);
    word(p, M::And, 0xff);
    for _ in 0..6 {
        emit(p, M::Asl, A::Accumulator, O::None);
    }
    implied(p, M::Clc);
    abs(p, M::Adc, DATA);
    implied(p, M::Clc);
    word(p, M::Adc, SPRITE_VRAM);
    emit(p, M::Lsr, A::Accumulator, O::None);
    abs(p, M::Sta, DATA);
    abs(p, M::Lda, BLOCKS);
    word(p, M::And, 0xff);
    for _ in 0..6 {
        emit(p, M::Asl, A::Accumulator, O::None);
    }
    abs(p, M::Sta, DATA + 2);
    for half in 0..2u16 {
        abs(p, M::Lda, DESCRIPTORS);
        for _ in 0..3 {
            emit(p, M::Asl, A::Accumulator, O::None);
        }
        implied(p, M::Tax);
        m8(p);
        byte(p, M::Lda, 0);
        long_x(p, M::Sta, UPLOAD_LIST);
        m16(p);
        abs(p, M::Lda, DATA);
        if half == 1 {
            implied(p, M::Clc);
            word(p, M::Adc, 256);
        }
        long_x(p, M::Sta, UPLOAD_LIST + 1);
        abs(p, M::Lda, DATA + 2);
        long_x(p, M::Sta, UPLOAD_LIST + 3);
        implied(p, M::Tya);
        implied(p, M::Clc);
        word(p, M::Adc, 1 + 3 * half);
        implied(p, M::Tay);
        indirect(p, M::Lda);
        emit(
            p,
            M::Sta,
            A::Absolute,
            O::Word(u16::from(crate::sfc_body_tiles::GATHER_POINTER)),
        );
        implied(p, M::Iny);
        implied(p, M::Iny);
        m8(p);
        indirect(p, M::Lda);
        emit(
            p,
            M::Sta,
            A::Absolute,
            O::Word(u16::from(crate::sfc_body_tiles::GATHER_POINTER) + 2),
        );
        m16(p);
        implied(p, M::Tya);
        implied(p, M::Sec);
        word(p, M::Sbc, 3 + 3 * half);
        implied(p, M::Tay);
        implied(p, M::Phx);
        implied(p, M::Txa);
        emit(p, M::Lsr, A::Accumulator, O::None);
        emit(p, M::Lsr, A::Accumulator, O::None);
        implied(p, M::Tax);
        long_x(p, M::Lda, stages);
        implied(p, M::Plx);
        long_x(p, M::Sta, UPLOAD_LIST + 5);
        implied(p, M::Pha);
        m8(p);
        byte(p, M::Lda, crate::sfc_body_tiles::STAGE_BANK);
        long_x(p, M::Sta, UPLOAD_LIST + 7);
        m16(p);
        implied(p, M::Pla);
        implied(p, M::Phx);
        implied(p, M::Phy);
        abs(p, M::Ldx, DATA + 2);
        implied(p, M::Phd);
        implied(p, M::Pha);
        word(p, M::Lda, 0);
        implied(p, M::Tcd);
        implied(p, M::Pla);
        emit(p, M::Jsl, A::AbsoluteLong, O::Long(gather));
        implied(p, M::Pld);
        implied(p, M::Ply);
        implied(p, M::Plx);
        abs(p, M::Inc, DESCRIPTORS);
    }
    m8(p);
    abs(p, M::Ldx, CELL);
    p.label("bdo_cache_name");
    long_x(p, M::Lda, cache(3));
    for _ in 0..5 {
        emit(p, M::Asl, A::Accumulator, O::None);
    }
    abs(p, M::Sta, SLOT_FOUND);
    long_x(p, M::Lda, cache(4));
    emit(p, M::Asl, A::Accumulator, O::None);
    implied(p, M::Clc);
    abs(p, M::Adc, SLOT_FOUND);
    abs(p, M::Sta, SLOT_FOUND);
    abs(p, M::Stz, SLOT_FOUND + 1);
    implied(p, M::Rts);
    p.label("bdo_cache_fail")
        .assume_mode(CpuMode::NATIVE_M8_X16);
    long(p, M::Lda, KNOWN);
    br(p, M::Bne, "bdo_cache_none");
    long(p, M::Lda, MEMO_NEXT);
    m16(p);
    word(p, M::And, 0xff);
    implied(p, M::Tax);
    m8(p);
    abs(p, M::Lda, DATA);
    long_x(p, M::Sta, MEMO_RESOURCE);
    abs(p, M::Lda, SHEET_FRAME);
    long_x(p, M::Sta, MEMO_FRAME);
    abs(p, M::Lda, DATA + 1);
    long_x(p, M::Sta, MEMO_CHUNK);
    implied(p, M::Inx);
    implied(p, M::Txa);
    byte(p, M::And, (MEMO_KEYS - 1) as u8);
    long(p, M::Sta, MEMO_NEXT);
    long(p, M::Lda, MEMO_COUNT);
    byte(p, M::Cmp, MEMO_KEYS as u8);
    br(p, M::Bcs, "bdo_cache_none");
    emit(p, M::Inc, A::Accumulator, O::None);
    long(p, M::Sta, MEMO_COUNT);
    p.label("bdo_cache_none")
        .assume_mode(CpuMode::NATIVE_M8_X16);
    byte(p, M::Lda, 0xff);
    abs(p, M::Sta, SLOT_FOUND);
    abs(p, M::Sta, SLOT_FOUND + 1);
    implied(p, M::Rts);
}
